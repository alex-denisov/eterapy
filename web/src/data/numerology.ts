/**
 * Нумерология Пифагора — расчёт числа жизненного пути
 */
export function lifePathNumber(birthDate: string): number {
  // birthDate в формате YYYY-MM-DD
  const digits = birthDate.replace(/-/g, "").split("").map(Number);
  let sum = digits.reduce((a, b) => a + b, 0);

  // Мастер-числа: 11, 22, 33 не редуцируем
  while (sum > 9 && sum !== 11 && sum !== 22 && sum !== 33) {
    sum = sum
      .toString()
      .split("")
      .map(Number)
      .reduce((a, b) => a + b, 0);
  }
  return sum;
}

