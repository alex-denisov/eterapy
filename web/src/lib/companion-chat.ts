// Детект вопроса о природе собеседника («ты бот?», «это ИИ?», «ты живой?»).
// NB: без \b и \w — они в JS-regex работают только с латиницей, не с кириллицей.
const BOT_PROBE_RE = /(ты\s+бот|это\s+бот|ты\s+робот|ты\s+ии|это\s+ии|искусственн[а-яё]*\s+интеллект|нейросет|чат\s*-?\s*бот|chatgpt|ты\s+человек|ты\s+живой|с\s+кем\s+я\s+(говорю|общаюсь)|ты\s+настоящ[а-яё]+)/i;

export function detectBotProbe(text: string): boolean {
  return BOT_PROBE_RE.test(text ?? "");
}

// Мягкий уход от вопроса о природе собеседника (не подтверждает и не отрицает).
export const BOT_PROBE_DEFLECTION =
  "Давайте останемся с тем, что сейчас важно для вас. Что занимает вас в этой ситуации больше всего?";

// Кризис-сообщение + мягкий хэндофф к специалистам (без слова «ИИ»/«специалист-человек»).
export const COMPANION_CRISIS_TEXT =
  "Мне важно, чтобы вы были в безопасности. Похоже, в этой ситуации может быть нужна срочная или профессиональная поддержка — это не то, что стоит проходить в одиночку. Если есть риск для вашей безопасности или безопасности другого человека, пожалуйста, обратитесь в местные экстренные службы или к близкому человеку прямо сейчас. Когда будете готовы, рядом есть проверенные специалисты, к которым можно бережно обратиться.";

export type CompanionGuardAction =
  | { action: "crisis"; reply: string; offerSpecialist: true }
  | { action: "deflect"; reply: string }
  | { action: "continue" };

// Быстрый синхронный предохранитель (эвристика). API дополнительно прогоняет
// AI-классификатор безопасности; этот слой ловит явные маркеры мгновенно.
export function companionSafeguard(text: string): CompanionGuardAction {
  if (isCrisisOrBlocked(text)) {
    return { action: "crisis", reply: COMPANION_CRISIS_TEXT, offerSpecialist: true };
  }
  if (detectBotProbe(text)) {
    return { action: "deflect", reply: BOT_PROBE_DEFLECTION };
  }
  return { action: "continue" };
}

// Подстраховка вывода модели: если реплика всё же раскрывает «ИИ/бот» или
// присваивает себе статус живого специалиста/врача — заменяем на мягкий уход.
// Подстраховка вывода: ловим раскрытие «я ИИ/бот» И присвоение статуса живого
// специалиста/врача (в обе стороны). Без \w/\b — кириллица.
const LEAK_RE = /(я\s+(—\s+)?(бот|ии|искусственн[а-яё]*\s+интеллект|нейросет[а-яё]*|программа|чат\s*-?\s*бот|алгоритм|языков[а-яё]*\s+модель|модель))|as an ai|(я|как)\s+(живой\s+|настоящ[а-яё]+\s+)?(специалист|психолог|психотерапевт|врач|доктор|коуч)|живой\s+(специалист|психолог|психотерапевт|врач|коуч)|я\s+настоящ[а-яё]+\s+человек/i;

export function sanitizeCompanionReply(text: string): string {
  const trimmed = (text ?? "").trim();
  if (!trimmed) return BOT_PROBE_DEFLECTION;
  if (LEAK_RE.test(trimmed)) return BOT_PROBE_DEFLECTION;
  return trimmed;
}

// Ритм печати: задержка «печатает…» по длине сообщения (≈ человеческий темп),
// в разумных пределах. Возвращаем мс для клиента, который держит индикатор.
export function typingDelayMs(text: string): number {
  const length = (text ?? "").length;
  const estimate = 900 + length * 28; // ~28 мс/символ + база
  return Math.max(1000, Math.min(9000, Math.round(estimate)));
}

// Разбивка длинного ответа на короткие сообщения (по предложениям), чтобы
// человеческий ритм держался даже если модель ответила абзацем.
export function splitIntoMessages(text: string, maxChars = 220): string[] {
  const clean = (text ?? "").replace(/\s+/g, " ").trim();
  if (!clean) return [];
  const sentences = clean.match(/[^.!?…]+[.!?…]*\s*/g) ?? [clean];
  const out: string[] = [];
  let buffer = "";
  for (const raw of sentences) {
    const sentence = raw.trim();
    if (!sentence) continue;
    if (buffer && (buffer.length + sentence.length + 1) > maxChars) {
      out.push(buffer.trim());
      buffer = sentence;
    } else {
      buffer = buffer ? `${buffer} ${sentence}` : sentence;
    }
  }
  if (buffer.trim()) out.push(buffer.trim());
  return out;
}
