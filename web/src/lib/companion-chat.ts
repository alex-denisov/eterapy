// Детект вопроса о природе собеседника («ты бот?», «это ИИ?», «ты живой?»).
// NB: без \b и \w — они в JS-regex работают только с латиницей, не с кириллицей.
const BOT_PROBE_RE = /(ты\s+бот|это\s+бот|ты\s+робот|ты\s+ии|это\s+ии|искусственн[а-яё]*\s+интеллект|нейросет|чат\s*-?\s*бот|chatgpt|ты\s+человек|ты\s+живой|с\s+кем\s+я\s+(говорю|общаюсь)|ты\s+настоящ[а-яё]+)/i;

export function detectBotProbe(text: string): boolean {
  return BOT_PROBE_RE.test(text ?? "");
}

// Мягкий уход от вопроса о природе собеседника (не подтверждает и не отрицает).
