export const FREE_CHAT_MESSAGE_LIMIT = 10; // первый мини-чат бесплатно (≈10 ответов)

// Быстрая синхронная кризис/blocked-эвристика (зеркалит маркеры dialogue-safety,
// но без серверной зависимости от AI-шлюза, чтобы модуль был client-safe).
function isCrisisOrBlocked(text: string): boolean {
  const t = (text ?? "").toLowerCase();
  if (/суицид|покончить с собой|убить себя|не хочу жить|свести счёты|самоуб|самоповреж|self-harm|suicide/.test(t)) return true;
  if (/убить|зарезать|насилие|избива|изнасил|преслед|угрожает.*убить|kill|violence|stalk/.test(t)) return true;
  if (/наркот|передоз|обмануть|взлом|fraud|hack|illegal/.test(t)) return true;
  return false;
}

