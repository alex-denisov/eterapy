function promptSections(input: {
  guardrail?: string;
  role: string;
  task: string;
  format: string;
  restrictions: string;
  extra?: string[];
}) {
  return [
    input.guardrail ?? COMMON_GUARDRAIL,
    `Роль: ${input.role}`,
    `Задача: ${input.task}`,
    `Формат результата: ${input.format}`,
    `Ограничения: ${input.restrictions}`,
    ...(input.extra ?? []),
  ].join("\n\n");
}

