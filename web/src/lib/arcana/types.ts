export type ArcanaPosition = {
  /** Название позиции так, как её ищут: «в центре матрицы», «под сердцем». */
  title: string;
  text: string;
};

export type ArcanaGuide = {
  /** Энергия 1…22. Совпадает с номером Старшего аркана. */
  number: number;
  /** Имя аркана в системе Матрицы судьбы. */
  name: string;
  /** Slug записи библиотеки — единственный адрес этого материала. */
  slug: string;
  heading: string;
  /** Прямой ответ в первом экране: что это за энергия, без предисловий. */
  answer: string;
  /** О чём эта энергия по сути — три опоры трактовки. */
  essence: readonly string[];
  /** Проявления «в плюсе» — так ищут: «8 аркан в плюсе». */
  strengths: readonly string[];
  /** Проявления «в минусе». */
  distortions: readonly string[];
  /** Позиции матрицы: центр, под сердцем, внешний квадрат, линии, род. */
  positions: readonly ArcanaPosition[];
  /** «N аркан на год» — возрастной период, а не гороскоп на календарный год. */
  year: string;
  /** «N аркан в совместимости» — энергия в матрице пары. */
  compatibility: string;
  /** Разночтения нумерации и названий, если они у этого аркана есть. */
  confusion?: string;
  /** Граница ответственности: где трактовка перестаёт быть уместной. */
  boundary: string;
  related: ReadonlyArray<{ href: string; label: string }>;
};
