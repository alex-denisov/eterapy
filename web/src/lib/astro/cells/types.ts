/**
 * B711 · Модель ячейки расчётной сетки «планета × знак».
 *
 * ⚠ ЗАЧЕМ ДВЕ ОСИ, А НЕ 120 ТЕКСТОВ. Сетка из 120 адресов, где каждый текст
 * написан с нуля, не сойдётся: её никто не допишет. Сетка, где текст
 * размножен подстановкой имён, — это дорвей, и её отфильтруют (scaled content
 * abuse). Поэтому модель разделена: ось планеты и ось знака дают ОБЩЕЕ (о чём
 * вообще эта планета, как вообще действует этот знак), а ячейка обязана
 * добавить СВОЁ — прямой ответ, напряжение конкретной пары и вопросы, которые
 * задают именно про неё. Без полей ячейки страница физически не собирается:
 * тип не даёт их пропустить.
 *
 * ⚠ ТРЕТЬЯ ЧАСТЬ СТРАНИЦЫ НЕ ЖИВЁТ ЗДЕСЬ ВООБЩЕ. Таблица периодов считается
 * `lib/astro/sign-transits` из эфемерид на сборке. Это то, чего нет у
 * пересказчиков, и это единственная часть, которую нельзя написать руками.
 *
 * Модуль — чистые данные без React: его читают и маршрут, и прогоны.
 */

/** Ось «планета»: 10 светил. Ключи совпадают с `PLANET_BODIES` в `../ecliptic`. */
export type PlanetAxis = {
  key: string;
  /** Именительный падеж: «Луна». */
  name: string;
  /** Часть адреса: `luna` в `luna-v-skorpione`. */
  slugPart: string;
  glyph: string;
  /**
   * Род имени светила. Нужен не для красоты: «Луна была», «Меркурий был»,
   * «Солнце было» — одна и та же фраза шаблона иначе выдаст «Меркурий была»
   * на девяти строках сетки из десяти.
   */
  gender: "m" | "f" | "n";
  /** О чём эта планета отвечает. Входит в прямой ответ страницы. */
  domain: string;
  /** Вопрос, на который отвечает положение планеты в знаке. */
  question: string;
  /** Как быстро планета проходит знак — человеческой фразой, для таблицы. */
  pace: string;
  /** Ширина окна таблицы периодов в годах. Луне хватает года, Плутону — нет. */
  windowYears: number;
  /** Частая подмена смысла: чем эту планету ошибочно считают. */
  misreading: string;
};

/** Ось «знак»: 12 знаков. Ключи совпадают с `ZODIAC_SIGNS`. */
export type SignAxis = {
  key: string;
  /** Именительный: «Скорпион». */
  name: string;
  /** Предложный: «Скорпионе» — заголовок собирается как «Луна в Скорпионе». */
  prepositional: string;
  /**
   * Предлог перед предложным падежом. У одного знака из двенадцати он другой —
   * «во Льве», а не «в Льве». Хранится, потому что это исключение, а не
   * правило: то же различие уезжает и в адрес (`luna-vo-lve`).
   */
  preposition: "в" | "во";
  /** Часть адреса: `skorpione`. */
  slugPart: string;
  glyph: string;
  element: string;
  /** Крест: кардинальный / фиксированный / мутабельный. */
  modality: string;
  /** Как этот знак вообще обходится с тем, что ему поручено. */
  manner: string;
};

export type GridFaq = { question: string; answer: string };

/**
 * Ячейка сетки. Всё, что здесь перечислено, пишется под конкретную пару:
 * общие формулировки осей уже сказаны выше по странице, и повторять их —
 * значит превращать страницу в шаблон.
 */
export type GridCell = {
  planetKey: string;
  signKey: string;
  /**
   * Прямой ответ в 40–60 слов. Стоит первым абзацем и уходит в описание
   * страницы: именно его извлекают и цитируют ИИ-движки (бриф B701).
   */
  answer: string;
  /** Что даёт это сочетание. Три пункта, каждый про наблюдаемое поведение. */
  plus: readonly string[];
  /** Чем оно оборачивается. Три пункта, не «плохие черты», а цена сильной стороны. */
  minus: readonly string[];
  /** Напряжение ИМЕННО этой пары: чего планета хочет и что знак с этим делает. */
  tension: string;
  /** Один проверяемый шаг, а не совет «работать над собой». */
  firstStep: string;
  /** Подзапросы кластера: «у женщины», «у мужчины», «в отношениях», «когда». */
  faqs: readonly GridFaq[];
};
