const PLANET_BY_KEY = new Map(PLANET_AXES.map((axis) => [axis.key, axis]));
const SIGN_BY_KEY = new Map(SIGN_AXES.map((axis) => [axis.key, axis]));

export function planetAxis(key: string): PlanetAxis {
  const axis = PLANET_BY_KEY.get(key);
  if (!axis) throw new Error(`Неизвестное светило сетки: ${key}`);
  return axis;
}

export function signAxis(key: string): SignAxis {
  const axis = SIGN_BY_KEY.get(key);
  if (!axis) throw new Error(`Неизвестный знак сетки: ${key}`);
  return axis;
}

/** Окончание прошедшего времени по роду светила: «был», «была», «было». */
export function planetPast(planet: PlanetAxis, stem: string): string {
  return `${stem}${planet.gender === "f" ? "а" : planet.gender === "n" ? "о" : ""}`;
}

/** «ваш Меркурий», «ваша Луна», «ваше Солнце». */
export function planetPossessive(planet: PlanetAxis): string {
  return planet.gender === "f" ? "ваша" : planet.gender === "n" ? "ваше" : "ваш";
}

/**
 * Текстовое начертание символа.
 *
 * Знаки зодиака (U+2648…U+2653) в системных шрифтах по умолчанию цветные
 * эмодзи: живая проверка на 375 px показала ♏ в заголовке цветной плашкой
 * рядом с типографским ☽. Селектор VS15 просит текстовое начертание — прогоны
 * этого не видят вообще, ловится только браузером.
 */
export function textGlyph(glyph: string): string {
  return `${glyph}︎`;
}
