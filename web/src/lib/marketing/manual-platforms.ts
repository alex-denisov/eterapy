/**
 * B654 — площадки без пути автоматического выпуска.
 *
 * ⚠ B742 — СПИСОК ПУСТ, И ЭТО СОСТОЯНИЕ, А НЕ ЗАГОТОВКА. Ручной площадкой была
 * одна — Reddit; решением владельца 2026-09-12 она убрана из контура целиком.
 * У всех оставшихся площадок есть автоматическая дорога наружу, поэтому
 * `approvedStatusForPlatform` сейчас всегда отвечает `SCHEDULED`.
 *
 * Механизм оставлен ЖИВЫМ, а не удалён, по двум причинам, каждой достаточно:
 * в реестре прода лежат строки в статусе `MANUAL`, заведённые до удаления, и
 * их читают снимок конвейера и таблица публикаций; а следующая площадка без
 * API попадёт сюда одной строкой вместо повторного разбирательства с четырьмя
 * механизмами ниже.
 *
 * ЗАЧЕМ ОТДЕЛЬНОЕ СОСТОЯНИЕ. Утверждённый материал для такой площадки вставал в
 * `SCHEDULED`, и дальше срабатывали три механизма подряд, каждый из которых
 * по-своему прав:
 *
 *  • выпуск брал строку, коннектор отвечал «не настроен», площадка уходила в
 *    `publish-hold` — инцидент, которого никто не собирается чинить;
 *  • сторож просроченного `SCHEDULED` каждые полчаса произносил вслух
 *    «публикации не появляются»;
 *  • строка держала слот контент-плана, не будучи выпущенной ни разу
 *    (`project_burned_content_plan_slots`).
 *
 * `MANUAL` говорит правду: материал готов, ждёт человека, и ни выпуск, ни
 * сторож его не трогают. Это НЕ отказ и НЕ пауза — текст годен, отсутствует
 * только автоматическая дорога наружу.
 */

export const MARKETING_MANUAL_PLATFORMS: ReadonlySet<string> = new Set<string>();

/** Состояние «написано, утверждено, ждёт человека». */
export const MARKETING_MANUAL_STATUS = "MANUAL";

export function marketingPlatformNeedsManualPublishing(platform: string): boolean {
  return MARKETING_MANUAL_PLATFORMS.has(platform.trim().toLowerCase());
}

/**
 * Состояние, в которое встаёт утверждённый НЕразговорный материал.
 *
 * Разговорный (комментарий, ответ на входящее) сюда не попадает: у него своя
 * дорога через премодерацию, и на ручных площадках он тоже ждёт человека —
 * но уже как `REVIEW`, где человек и так стоит в процессе.
 */
export function approvedStatusForPlatform(platform: string): string {
  return marketingPlatformNeedsManualPublishing(platform)
    ? MARKETING_MANUAL_STATUS
    : "SCHEDULED";
}
