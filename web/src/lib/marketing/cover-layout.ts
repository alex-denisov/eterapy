/**
 * B727 — одно правило выбора раскладки обложки на два места вызова.
 *
 * До этого решение «диалоговый мокап или графика» принимали ДВА независимых
 * куска кода — `agent.ts` при утверждении материала и маршрут
 * `api/marketing/media/[key]` при отрисовке, — и оба спрашивали ЗАГОЛОВОК:
 * есть ли в нём `«` или слова «диалог|переписк|сообщен|написал|молчани|чат».
 *
 * Замер реестра прода 2026-09-07 показал, почему это не сработало ни разу:
 *
 * | признак               | строк из 226 |
 * |-----------------------|--------------|
 * | заголовок под регулярку |  8 (3,5 %) |
 * | `«` в заголовке        |  6 (2,7 %) |
 * | `«` в ТЕЛЕ поста       | 99 (45 %)  |
 * | реально прикреплено `chat_mockup` | 0 |
 *
 * Персона Ани (B723) ставит цитату собеседника в тело поста, а заголовок несёт
 * поисковый запрос. Признак искали не там, где он есть.
 *
 * Поэтому правило теперь смотрит на тело и ЗАБИРАЕТ ОТТУДА саму реплику: мокап
 * печатает то, что человек действительно написал в переписке, а не SEO-строку
 * заголовка. Заголовочные маркеры оставлены вторым входом — материал, у которого
 * разбор диалога вынесен в заголовок, тоже заслуживает мокапа.
 */

export type CoverLayout = "art" | "chat_mockup";

/** Все кавычки-ёлочки в тексте: выбирать будем лучшую, а не первую. */
const QUOTE_PATTERN = /«\s*([^»]{3,160})\s*»/gu;

/**
 * Реплика — это ФРАЗА, а не термин в кавычках.
 *
 * Замер реестра прода 2026-09-07 показал, зачем нужен этот фильтр: кавычки есть
 * у 100 материалов из 222, но добрая половина — это названия и слова
 * («Маг», «Жрица», «Смерть», «вспыльчивый», «затапливать», «программа долгов»).
 * В пузыре мессенджера такое читается не как чужое сообщение, а как ошибка
 * вёрстки: никто не пишет вам в час ночи одно слово «Жрица».
 *
 * Три условия отделяют речь от терминологии на реальных данных:
 *   • минимум два слова — односложное «обидела» отсекается;
 *   • от 12 знаков — «вернётся ли он» коротко даже для двух слов;
 *   • заглавная в начале ИЛИ знак конца фразы — так проходят «Что я опять
 *     сделал не так?» и «Ты стала какой-то чужой», но не «бороться за
 *     отношения» и не «расставание и возврат».
 *
 * По этому правилу мокап получает 47 материала из 222 (21 %) — против 100 при
 * проверке «есть кавычки», где больше половины были бы терминами.
 */
function isUtterance(quote: string): boolean {
  // Наш собственный призыв в кавычках репликой не считается: иначе мокап
  // напечатает как «входящее сообщение» нашу же ссылку.
  if (/https?:\/\/|eterapy\.com|utm_/i.test(quote)) return false;
  if (!quote.includes(" ")) return false;
  if (quote.length < 12) return false;
  return /^[А-ЯЁA-Z]/u.test(quote) || /[?!.…]$/u.test(quote);
}

/**
 * Первая реплика материала, похожая на живую речь.
 *
 * Перебираются ВСЕ кавычки, а не только первые: у материала про арканы первым
 * идёт название карты, а настоящая фраза человека — абзацем ниже. Проверка
 * «первое совпадение» отдала бы такой материал графике.
 */
export function dialogueQuoteFrom(text: string | null | undefined): string | null {
  if (!text) return null;
  for (const match of text.matchAll(QUOTE_PATTERN)) {
    const quote = match[1].replace(/\s+/g, " ").trim();
    if (isUtterance(quote)) return quote;
  }
  return null;
}

/**
 * Раскладка обложки и реплика для неё.
 *
 * `messageText` заполняется только для мокапа: у графической раскладки его
 * некуда положить, и пустое поле честнее выдуманного.
 */
export function coverLayoutFor(input: {
  title: string;
  body?: string | null;
  cluster?: string | null;
}): { layout: CoverLayout; messageText: string | null } {
  const quote = dialogueQuoteFrom(input.body);
  if (quote) {
    return { layout: "chat_mockup", messageText: quote };
  }

  const titleQuote = dialogueQuoteFrom(input.title);
  if (titleQuote) {
    return { layout: "chat_mockup", messageText: titleQuote };
  }

  /**
   * B731 (стенд 2026-09-08) — БЕЗ РЕПЛИКИ МОКАПА НЕ БЫВАЕТ.
   *
   * Прежде заголовочный маркер отдавал мокап с пустой репликой, и в пузырь
   * вставал ЗАГОЛОВОК СТАТЬИ: «Что показывает натальная карта: разбор без
   * предсказаний» — прислано в 14:08. Так не пишет ни один живой человек, и
   * одного такого пузыря достаточно, чтобы вся картинка читалась как
   * нарисованная. Требование владельца — «хоть немного непохож» уже провал.
   *
   * Поэтому маркер в заголовке больше не открывает мокап сам по себе: он
   * означает «материал про переписку», а не «у нас есть что напечатать в
   * пузыре». Такой материал уходит на графический шаблон — честную обложку без
   * подделки. По замеру реестра прода эта ветка давала 8 строк из 226 (3,5 %),
   * и все они рисовали в пузыре заголовок.
   */
  return { layout: "art", messageText: null };
}
