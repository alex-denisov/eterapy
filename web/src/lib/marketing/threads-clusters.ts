/** Тестовое плечо крепкой лексики: каждый десятый пост Threads (решение владельца). */
export const PROFANITY_ARM_PERIOD = 10;

export const PROFANITY_ARM_RULE =
  "Тестовое плечо: допустимо одно-два крепких слова (мат) для эмоции, БЕЗ оскорбления людей, групп и без угроз. Остальное по правилам формата.";

export function techniqueFor(day: number, sequence: number, clusterIndex: number): Technique {
  return pick(TECHNIQUES, day * 5 + sequence * 3 + clusterIndex);
}

/** Слот входит в плечо крепкой лексики (1 пост из 10 по сквозному номеру). */
export function isProfanityArm(day: number, sequence: number): boolean {
  return (day * 4 + sequence) % PROFANITY_ARM_PERIOD === PROFANITY_ARM_PERIOD - 1;
}

