/**
 * B769 — стоп-проверки кода для постов Threads (слой проверяющего, который не
 * ошибается в сторону «режет хорошее»).
 *
 * Замер 2026-10-12 на 79 постах с оценками владельца: каждая из четырёх проверок
 * режет не больше одного поста из 22 с оценкой ≥ 8, поэтому их можно держать в
 * кругах правки как замечания. LLM-проверяющие такой точности не дали (см.
 * `threads-checker.ts` и раздел замера в тикете B769) и в конвейер не включены.
 *
 * Все проверки — замечания кругов правки, не отказы: на выпуске материал они не
 * режут (владелец всё равно видит пост в B764).
 */

import type { LimitViolation } from "@/lib/marketing/platform-limits";

const B = "(?<![а-яё])";
const E = "(?![а-яё])";

/** Имена героев, которых автор любит придумывать; герой без роли — «Елена пишет» вместо «начальница пишет». */
const HERO_NAMES = [
  "Елена", "Никита", "Аня", "Анна", "Катя", "Маша", "Марина", "Олег", "Саша", "Дима", "Игорь",
  "Лена", "Света", "Ира", "Оля", "Вика", "Настя", "Котлета",
];
const ROLE_WORDS = /(?<![а-яё])(?:бывш[а-яё]*|парень|парня|муж|мужа|подруг[а-яё]*|мам[а-яё]*|начальниц[а-яё]*|коллег[а-яё]*|сестр[а-яё]*|кот|кота|кошк[а-яё]*|свекров[а-яё]*|мой|моя|мою|наш[а-яё]*|клиентк[а-яё]*)(?![а-яё])/i;

/** Книжные и «психологические» слова, которых живой человек в переписке не говорит. */
const BOOKISH = new RegExp(
  `${B}(?:осознанн[а-яё]*|манифест[а-яё]*|трансформаци[а-яё]*|масштаб[а-яё]*|дискомфорт[а-яё]*|коммуникаци[а-яё]*|взаимодействи[а-яё]*|ресурсн[а-яё]*|деструктив[а-яё]*|обесценива[а-яё]*|токсичн[а-яё]*|триггер[а-яё]*|инсайт[а-яё]*|рефлекси[а-яё]*|паттерн[а-яё]*|нарратив[а-яё]*)${E}`,
  "iu",
);

/** «Я» и глагол прошедшего времени мужского рода: голос бренда женский. */
const MASCULINE_I = new RegExp(`${B}я\\s+(?:\\S+\\s+)?\\S*(?:ал|ил|ел|ёл|ул|ыл|ол)${E}`, "iu");

function heroWithoutRole(text: string): string | null {
  for (const name of HERO_NAMES) {
    const match = new RegExp(`${B}${name}${E}`, "u").exec(text);
    if (!match) continue;
    const context = text.slice(Math.max(0, match.index - 40), match.index + name.length + 10);
    if (!ROLE_WORDS.test(context)) return name;
  }
  return null;
}

function tailAfterQuestion(text: string): boolean {
  const last = text.trim().split(/\r?\n/).map((line) => line.trim()).filter(Boolean).at(-1) ?? "";
  return /\?\s+\S/u.test(last) && !/\?\s*(?:[.!…]+|[)"»]+)?\s*$/u.test(last);
}

export function threadsStopFindings(text: string): LimitViolation[] {
  if (!text.trim()) return [];
  const findings: LimitViolation[] = [];
  const add = (rule: string, issue: string, brief: string) =>
    findings.push({ kind: "contract", rule, issue, brief });

  // Слово в «кавычках» — чужая речь, которую сцена показывает, а не язык рассказчика.
  const bookish = BOOKISH.exec(text.replace(/«[^»]*»/gu, " "));
  if (bookish) {
    add("threads-bookish-word", `Книжное слово «${bookish[0]}»: так не говорят.`, `Замени «${bookish[0]}» словами, которыми это сказала бы подруга в переписке.`);
  }
  const masculine = MASCULINE_I.exec(text);
  if (masculine) {
    add("threads-masculine-voice", `Мужской род у рассказчика: «${masculine[0]}». Голос бренда женский.`, "Переведи рассказчика в женский род («я сказала», «я решила»).");
  }
  const name = heroWithoutRole(text);
  if (name) {
    add("threads-name-without-role", `Герой «${name}» назван по имени без роли: читателю не за что зацепиться.`, `Назови героя по роли (бывший, начальница, подруга, свекровь) вместо «${name}».`);
  }
  if (tailAfterQuestion(text)) {
    add("threads-question-tail", "После вопроса в последней строке есть довесок.", "Вопрос — последнее, что читает человек: убери хвост после вопросительного знака.");
  }
  return findings;
}

