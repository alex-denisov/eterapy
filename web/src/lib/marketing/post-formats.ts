const FORMATS_BY_LABEL = new Map(THREADS_FORMATS.map((format) => [format.label, format]));

export function postFormatByLabel(label: string | null | undefined): PostFormat | null {
  return label ? FORMATS_BY_LABEL.get(label) ?? null : null;
}

/**
 * Формат слота по номеру суток и порядковому номеру слота.
 *
 * Веса разворачиваются в ленту повторов и берутся по остатку: доля формата
 * задаётся ЧИСЛОМ в одном месте, а не порядком в списке. Множитель 3 у номера
 * суток расцепляет соседние дни — без него два слота одних суток и два слота
 * следующих шли бы одной полосой.
 */
const WEIGHTED_FORMATS: readonly PostFormat[] = THREADS_FORMATS.flatMap(
  (format) => Array.from({ length: format.weight }, () => format),
);

export function threadsFormatFor(day: number, sequence: number): PostFormat {
  const size = WEIGHTED_FORMATS.length;
  const position = (((day * 3 + sequence) % size) + size) % size;
  return WEIGHTED_FORMATS[position];
}
