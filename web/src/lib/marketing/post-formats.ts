const LIBRARIES: Record<FormatPlatform, readonly PostFormat[]> = {
  threads: THREADS_FORMATS,
  telegram: TELEGRAM_FORMATS,
  vk: VK_FORMATS,
  instagram: INSTAGRAM_FORMATS,
  dzen: DZEN_FORMATS,
};

export function formatsFor(platform: FormatPlatform): readonly PostFormat[] {
  return LIBRARIES[platform];
}

const FORMATS_BY_LABEL = new Map<string, PostFormat>();
for (const platform of Object.keys(LIBRARIES) as FormatPlatform[]) {
  for (const format of LIBRARIES[platform]) {
    FORMATS_BY_LABEL.set(`${platform}:${format.label}`, format);
    // Без площадки — первый встретившийся: старые строки реестра несут только
    // название формата, и для них достаточно любого совпадения.
    if (!FORMATS_BY_LABEL.has(format.label)) FORMATS_BY_LABEL.set(format.label, format);
  }
}

export function postFormatByLabel(
  label: string | null | undefined,
  platform?: FormatPlatform,
): PostFormat | null {
  if (!label) return null;
  if (platform) return FORMATS_BY_LABEL.get(`${platform}:${label}`) ?? null;
  return FORMATS_BY_LABEL.get(label) ?? null;
}

/**
 * Формат слота по номеру суток и порядковому номеру слота.
 *
 * Веса разворачиваются в ленту повторов, позиция в ленте берётся от
 * ПЕРЕМЕШАННОГО номера суток, а не от `day * k`: у арифметической прогрессии
 * шаг делит длину ленты, и площадка с одним слотом раз в двое суток (Instagram,
 * лента из 6) получала бы один и тот же формат вечно. Перемешивание —
 * детерминированное (одна дата → один формат при каждом пересчёте плана,
 * [[reference_sliding_window_positions_are_not_dates]]) и своё у каждой
 * площадки: одна дата не даёт один и тот же формат Telegram и VK.
 */
const WEIGHTED = new Map<FormatPlatform, readonly PostFormat[]>(
  (Object.keys(LIBRARIES) as FormatPlatform[]).map((platform) => [
    platform,
    LIBRARIES[platform].flatMap((format) => Array.from({ length: format.weight }, () => format)),
  ]),
);

const PLATFORM_SALT: Record<FormatPlatform, number> = {
  threads: 11,
  telegram: 23,
  vk: 37,
  instagram: 53,
  dzen: 71,
};

/** Целочисленное перемешивание (вариант xorshift/murmur-финализатора), детерминированное. */
function mix(value: number): number {
  let x = (value | 0) ^ 0x9e3779b9;
  x = Math.imul(x ^ (x >>> 16), 0x85ebca6b);
  x = Math.imul(x ^ (x >>> 13), 0xc2b2ae35);
  return (x ^ (x >>> 16)) >>> 0;
}

export function formatFor(platform: FormatPlatform, day: number, sequence: number): PostFormat {
  const lane = WEIGHTED.get(platform)!;
  const position = mix(day * 8 + sequence + PLATFORM_SALT[platform] * 1000) % lane.length;
  return lane[position];
}

/** Совместимость с B733: формат Threads по номеру суток. */
export function threadsFormatFor(day: number, sequence: number): PostFormat {
  return formatFor("threads", day, sequence);
}

/**
 * Требования формата ДЛЯ КОНКРЕТНОГО СЛОТА.
 *
 * У серийных форматов часть требований зависит от суток: оклик по знаку
 * обязан назвать знак, и знак должен быть один и тот же при каждом пересчёте
 * плана (от номера суток, не от позиции в окне).
 */
export function formatRulesFor(format: PostFormat, day: number): readonly string[] {
  if (format.label !== ZODIAC_CALLOUT_LABEL) return format.rules;
  const sign = zodiacSignFor(day);
  return [
    `Знак этого поста — ${sign}. Обращение к знаку по имени в первой строке обязательно; другие знаки не упоминаются.`,
    ...format.rules,
  ];
}
