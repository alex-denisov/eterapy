/**
 * B733 — ФОРМАТ ПОСТА КАК ОТДЕЛЬНАЯ СУЩНОСТЬ, А НЕ ДОГАДКА АВТОРА.
 *
 * Замер прода за 30 суток (B727): 142 поста, лучший по просмотрам — 66
 * (threads). Это не «немного не работает», это охват на уровне шума.
 *
 * Требование владельца 2026-09-08 дословно: «посты в Threads не обязательно
 * вообще должны иметь скриншоты, это может быть какой-то вопрос, какой-то хук,
 * вброс, что-то смешное, нужно проявить реальную креативность при создании этих
 * постов, а не просто шаблонный текст по одному и тому же сценарию и по одному
 * и тому же расписанию».
 *
 * Причина ровной ленты была не в модели. У слота есть ТЕМА, есть контракт
 * площадки, есть персона — и НЕТ понятия «форма поста». Поэтому всё выходило
 * одной формой: хук → разбор → мягкий вывод → CTA. Формат теперь объявлен
 * слотом, доезжает до автора И до редактора и несёт СВОИ требования: пост-шутка
 * не обязан нести пользу и призыв, и редактор не имеет права резать его за это
 * (B734 — там же снята формулировка `platformFit` «похоже на типичный пост»).
 *
 * ЧЕСТНО О КОРПУСЕ. Тикет просил собрать 30–50 живых образцов. Живая лента
 * Threads закрыта для машинного чтения (веб отдаёт заглушку входа), поэтому
 * конструкции ниже записаны по повторяющимся образцам жанра, а не выгружены из
 * ленты. Это гипотезы, и они помечены весами: доля формата — ручка, которую
 * поворачивает ЗАМЕР просмотров (B729 даёт числа), а не вкус.
 *
 * ТОН. Решение владельца 2026-09-08 дословно: «у нас тут нет никаких запретов
 * на контент […] мы — лучшие SMM-эксперты, которые могут и посмеяться над
 * собой, и над другими, и потоксичить». Поэтому в конструкциях нет смягчающих
 * оговорок. Остаются ровно два ограничения, и оба внешние:
 *   • правила площадки — Threads/Meta снимают за травлю конкретного человека и
 *     за оскорбления по защищённым признакам (это причина, по которой аккаунт
 *     может исчезнуть, а не наша щепетильность);
 *   • никаких реальных опознаваемых людей — выдуманная ситуация это материал,
 *     выдуманное свидетельство о живом человеке уже нет
 *     ([[feedback_demo_stats_become_fabrication]]).
 */

import type { ContentClass } from "@/lib/marketing/publish-windows";

/** Нужна ли формату картинка и какая. */
export type FormatMedia = "none" | "chat_mockup" | "art";

export interface PostFormat {
  /** Название формата. Оно же уходит в `notes` слота и в задачу автора. */
  label: string;
  /** Конструкция: что именно повторяется в постах этого вида. */
  construction: string;
  contentClass: ContentClass;
  /**
   * Доля формата в ленте. Веса целые и складываются: это ручка отбора по
   * факту — формат, который даёт просмотры, получает больший вес, а не
   * «нравится больше».
   */
  weight: number;
  media: FormatMedia;
  /**
   * Требования формата — уходят В ЗАДАЧУ и автору, и редактору.
   *
   * Здесь они формулируются РАЗРЕШЕНИЯМИ, а не запретами: редактор по своей
   * рубрике ждёт пользы, вывода и призыва, и без явного «этому формату они не
   * нужны» срежет ровно то, ради чего формат заведён.
   */
  rules: readonly string[];
  /** Живой образец конструкции — не для копирования, а чтобы задать форму. */
  example: string;
}

