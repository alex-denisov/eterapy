import type { ContentClass } from "@/lib/marketing/publish-windows";

/** Нужна ли формату картинка и какая. */
export type FormatMedia = "none" | "chat_mockup" | "art";

/** Продолжение поста ответом на самого себя. */
export type FormatReply = "forecast";

export type FormatPlatform = "threads" | "telegram" | "vk" | "instagram" | "dzen";

export interface PostFormat {
  /** Название формата. Оно же уходит в `notes` слота и в задачу автора. */
  label: string;
  /** Конструкция: что именно повторяется в постах этого вида. */
  construction: string;
  contentClass: ContentClass;
  /**
   * Доля формата в ленте. Веса целые и складываются: это ручка отбора по
   * факту — формат, который даёт просмотры, получает больший вес, а не
   * «нравится больше».
   */
  weight: number;
  media: FormatMedia;
  /**
   * Нужны ли материалу ссылка из плана и призыв.
   *
   * `false` — код НЕ дописывает адрес и НЕ чинит отсутствующий призыв на
   * последнем раунде; проверка `cta` для такого материала не выполняется.
   */
  link: boolean;
  /** Продолжение ответом на свой пост: автор пишет `replyText`. */
  reply?: FormatReply;
  /**
   * Требования формата — уходят В ЗАДАЧУ и автору, и редактору.
   *
   * Здесь они формулируются РАЗРЕШЕНИЯМИ, а не запретами: редактор по своей
   * рубрике ждёт пользы, вывода и призыва, и без явного «этому формату они не
   * нужны» срежет ровно то, ради чего формат заведён.
   */
  rules: readonly string[];
  /** Живой образец конструкции — не для копирования, а чтобы задать форму. */
  example: string;
}

