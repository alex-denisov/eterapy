/**
 * B705 — реестр ролей маркетингового контура.
 *
 * Требование владельца 2026-08-12 дословно: «Промты (системные промты) должны
 * быть у каждого из агентов (планировщик, писатель, редактор, публикатор,
 * SEO-специалист, SMM-специалист) … в системных промтах должны быть чётко
 * описаны роли и задачи каждого агента».
 *
 * Здесь живут ХАРТИИ ролей, а не тексты промтов: роль знает своё дело, свои
 * решения и — что важнее — границу, за которой начинается чужая работа.
 * Тексты собирает `agent-prompt.ts`, приклеивая хартию первым блоком. Обратной
 * зависимости нет намеренно: реестр не импортирует промты, иначе получится
 * цикл модулей.
 *
 * Почему граница `notMine` не украшение. Замер прода 2026-08-12 показал два
 * случая одной и той же болезни:
 *  - автор Threads читал правила шести площадок сразу и писал 718 символов при
 *    пределе 480 (§1 тикета);
 *  - один и тот же системный промт обслуживал автора ПОСТА и автора
 *    КОММЕНТАРИЯ: писателю поста уходили правила регистра чужой ветки, памяти
 *    разговора и премодерации входящего — работа, которой у него нет.
 * Оба случая — смешение контекстов. Роль без явной границы дописывает себе
 * чужую задачу, и это стоит круга редактуры.
 */

export type MarketingRoleId =
  | "planner"
  | "writer"
  | "editor"
  | "publisher"
  | "seo"
  | "smm";

/**
 * `model` — роль обращается к модели и обязана иметь системный промт.
 * `deterministic` — роль выполняется кодом. Промт ей не отправляется никуда:
 * хартия существует, чтобы граница ответственности была одна и та же в коде, в
 * суперадминке и в промтах соседних ролей, которые на неё ссылаются.
 */
export type MarketingRoleKind = "model" | "deterministic";

export interface MarketingRole {
  readonly id: MarketingRoleId;
  /** Как роль называет себя в первой строке промта. */
  readonly title: string;
  /** Что считается результатом роли. Одно предложение, проверяемое. */
  readonly mission: string;
  /** Решения, которые принимает только эта роль. */
  readonly decides: readonly string[];
  /** Чужая работа и роль, которой она принадлежит. */
  readonly notMine: readonly string[];
  /** Что роль получает на вход. */
  readonly inputs: readonly string[];
  /** Что роль отдаёт дальше и кому. */
  readonly handoff: string;
  /** Как часто роль работает — такт заметно разный, см. §9 тикета B705. */
  readonly cadence: string;
  readonly kind: MarketingRoleKind;
  /**
   * Фичи шлюза ИИ, под которыми живут промты роли в `ai_prompt_configs`.
   * У детерминированных ролей список пуст: обращений к модели у них нет, и
   * строка в реестре промтов показывала бы в суперадминке текст, который
   * никуда не уходит.
   *
   * У редактора их две: он судит и пост, и ответ человеку. Роль одна, а
   * промта два — потому что критерии разные, и мерить ответ человеку по
   * критериям поста он не может (ровно та же болезнь, что шесть площадок в
   * одном промте).
   */
  readonly features: readonly string[];
}

