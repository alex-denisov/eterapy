/**
 * B705 — «прислал не пост» это свойство ответа, а не брак материала.
 *
 * ПОЧЕМУ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Замер прода 2026-08-16 за 14 суток: 113 смертей
 * материалов против 3 выпусков за неделю. Разбор причин дословно из
 * `last_error` и `archive_reason`:
 *
 *   «автор вместо написания поста прислал технический лог своих размышлений
 *    на английском языке»
 *   «автор прислал техническую заглушку на английском языке вместо текста»
 *   «текст кандидата не является финишной версией поста, а содержит служебные
 *    комментарии»
 *   «Текст технически поврежден (оборван в начале и в середине), нечитаем»
 *
 * Каждая такая строка — материал, который прошёл ВЕСЬ конвейер: заплатили
 * автору за размышление вслух, заплатили редактору за то, чтобы он прочитал
 * английский лог и написал по-русски, что это не пост, потратили раунд из
 * бюджета материала — и материал умер по причине, к нему не относящейся.
 * Отвечала не тема и не промт, а модель, у которой протекла цепочка
 * рассуждений.
 *
 * ГРАНИЦА, ПО КОТОРОЙ ПРАВИЛО ПОПАДАЕТ СЮДА, та же, что у `draft-inspection`:
 * свойство считается БЕЗ понимания смысла. «Это русский текст или английский»,
 * «начинается ли строка со служебного маркера», «остались ли скобки-заглушки»
 * — считается. «Хорош ли пост» — нет, и это остаётся редактору.
 *
 * ЧТО ДЕЛАЕТ ОТКАЗ ЭТОГО МОДУЛЯ. Он бросается из `writerObject`, то есть
 * попадает в `parse` внутри `completeWithValidStructure`, и там разбор ответа
 * снимает с перебора ЭТОТ маршрут, а не материал: следующий провайдер получает
 * тот же запрос. Это ровно то же рассуждение, что у B695 «отказ дороги — не
 * вина материала»: черновика не было, судить нечего.
 *
 * ⚠ ЛОЖНОЕ СРАБАТЫВАНИЕ ЗДЕСЬ ДОРОЖЕ ПРОПУСКА. Отвергнутый ответ уже оплачен,
 * и на его месте будет обращение к другому провайдеру. Поэтому каждое правило
 * закрытое и узкое: маркеры привязаны к НАЧАЛУ строки, доля кириллицы меряется
 * только на достаточной длине, а «похоже на служебное» без явного маркера не
 * считается ничем.
 */

/**
 * Ниже какой доли кириллицы среди букв ответ перестаёт быть русским постом.
 *
 * Планка низкая намеренно: половина. Русский пост про «ИИ-психолог» или
 * «Human Design» законно несёт латиницу в терминах и в ссылке, и порог 0,8
 * убивал бы годные тексты. Английский лог рассуждений при этом даёт долю
 * кириллицы около нуля — промахнуться мимо половины он не может.
 */
const MIN_CYRILLIC_SHARE = 0.5;

/**
 * Короче этого текст не проверяется на язык вовсе.
 *
 * На двух десятках букв доля кириллицы — шум: подпись, хэштег или одно
 * английское название дают любую величину. Пустой и слишком короткий текст
 * ловится своей проверкой в `repairPublishableDraft` («writer safety block»).
 */
const MIN_LETTERS_FOR_LANGUAGE = 40;

/**
 * Начала строк, которыми модель выдаёт размышление вслух вместо ответа.
 *
 * Список закрытый и проверяется ТОЛЬКО в начале строки: «note» и «first»
 * внутри предложения — обычные слова, а строка, начатая с «Note:» или
 * «First, I need to», это служебная реплика и ничего больше.
 */
const REASONING_LINE_OPENERS = [
  "let me",
  "let's ",
  "i need to",
  "i should",
  "i will",
  "i'll ",
  "i'm going to",
  "we need to",
  "okay,",
  "okay so",
  "alright,",
  "first, i",
  "the user",
  "the task",
  "here's the",
  "here is the",
  "sure,",
  "sure!",
  "note:",
  "as an ai",
  "looking at",
  "based on the",
  "to summarize",
  "final answer",
  "мне нужно написать",
  "итак, задача",
  "вот пост:",
  "вот текст поста",
  "вот готовый пост",
];

/**
 * Обёртки цепочки рассуждений. Встречаются где угодно в тексте, а не только в
 * начале строки: думающая модель закрывает блок посреди ответа.
 */
const REASONING_TAGS = /<\/?(?:think|thinking|reasoning|scratchpad|analysis)\s*>/iu;

/**
 * Заглушки шаблона: текст, в котором осталось место «сюда подставить».
 *
 * `{{…}}` и `[…]` с русским глаголом-указанием — это незаполненный шаблон, а
 * не пост. Квадратные скобки сами по себе не запрещены: в русском тексте они
 * законно несут пояснение.
 */
const PLACEHOLDER_PATTERNS: ReadonlyArray<{ readonly rule: string; readonly probe: RegExp }> = [
  { rule: "moustache", probe: /\{\{[^}]{1,60}\}\}/u },
  { rule: "bracket-instruction", probe: /\[(?:вставь|вставить|вставьте|укажи|укажите|добавь|добавить|ваш|ваше|ваша|текст|описание|placeholder|insert|todo)[^\]]{0,60}\]/iu },
  { rule: "lorem", probe: /lorem ipsum/iu },
  { rule: "todo", probe: /^\s*(?:todo|fixme)\b/imu },
];

export interface WriterOutputRejection {
  /** Ключ правила — по нему видно в журнале, чем именно ответ не был постом. */
  rule: string;
  /** Причина в том виде, в каком она уходит в `failures` перебора провайдеров. */
  reason: string;
}

function lettersOf(text: string): { total: number; cyrillic: number } {
  let total = 0;
  let cyrillic = 0;
  for (const char of text) {
    if (!/\p{L}/u.test(char)) continue;
    total += 1;
    if (/\p{Script=Cyrillic}/u.test(char)) cyrillic += 1;
  }
  return { total, cyrillic };
}

/**
 * Текст без ссылок и без блоков кода: и то и другое законно латинское, и
 * считать их буквами при замере языка значило бы наказывать материал за
 * обязательную ссылку из плана.
 */
function languageSample(text: string): string {
  return text
    .replace(/https?:\/\/\S+/giu, " ")
    .replace(/```[\s\S]*?```/gu, " ")
    .replace(/`[^`]*`/gu, " ")
    .replace(/(?:^|\s)[#@][\p{L}\p{N}_]+/gu, " ");
}

/**
 * Ответ автора — законченный русский пост, или его не было вовсе.
 *
 * Возвращает `null`, когда возражений нет. Не бросает сама: решение, чем
 * считать отказ, принимает вызывающий (`writerObject` — недействительным
 * ответом маршрута).
 */
export function rejectNonPostWriterOutput(text: string): WriterOutputRejection | null {
  const trimmed = text.trim();
  if (!trimmed) {
    return { rule: "writer-empty", reason: "автор вернул пустой текст" };
  }

  if (REASONING_TAGS.test(trimmed)) {
    return {
      rule: "writer-reasoning-tag",
      reason: "в ответе осталась обёртка цепочки рассуждений (<think>…</think>) — это лог модели, а не пост",
    };
  }

  /*
   * Ответ целиком в блоке кода — это не пост, а выгрузка. Разбор JSON выше уже
   * снял бы обёртку, если внутри была структура; сюда доходит случай, когда
   * внутри блока лежит проза с разметкой.
   */
  if (/^```/u.test(trimmed) && /```\s*$/u.test(trimmed)) {
    return {
      rule: "writer-fenced-output",
      reason: "ответ целиком завёрнут в блок кода — это выгрузка, а не текст поста",
    };
  }

  const opener = REASONING_LINE_OPENERS.find((marker) =>
    trimmed.split("\n").some((line) => line.trim().toLowerCase().startsWith(marker)),
  );
  if (opener) {
    return {
      rule: "writer-reasoning-leak",
      reason: `строка ответа начинается со служебного маркера «${opener.trim()}» — модель размышляет вслух вместо текста поста`,
    };
  }

  const placeholder = PLACEHOLDER_PATTERNS.find(({ probe }) => probe.test(trimmed));
  if (placeholder) {
    return {
      rule: `writer-placeholder-${placeholder.rule}`,
      reason: "в тексте осталась незаполненная заглушка шаблона — это черновик формы, а не пост",
    };
  }

  const { total, cyrillic } = lettersOf(languageSample(trimmed));
  if (total >= MIN_LETTERS_FOR_LANGUAGE && cyrillic / total < MIN_CYRILLIC_SHARE) {
    const share = Math.round((cyrillic / total) * 100);
    return {
      rule: "writer-not-russian",
      reason: `текст не русский: кириллицы ${share}% от букв при пороге ${Math.round(MIN_CYRILLIC_SHARE * 100)}%`,
    };
  }

  return null;
}
