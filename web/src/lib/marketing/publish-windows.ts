/**
 * Ширина окна по классу — сколько материал остаётся собой, выйдя не вовремя.
 *
 * До этой правки ширина была одна на всё (`SLOT_WINDOW_MS` = 2 часа, B645).
 * Для карточки дня два часа — правда: смысл её в часе. Для статьи это ложь:
 * статья не портится оттого, что вышла в 12:00 вместо 09:30, зато переносится
 * в следующие сутки и теряет слот целиком.
 *
 * Верхняя граница у каждого значения одна и та же: окно класса не должно
 * дотянуться до следующего слота той же площадки в тот же день. Это свойство
 * проверяется тестом по всему плану, а не удерживается на глаз.
 */
const CLASS_TOLERANCE_MS: Record<ContentClass, number> = {
  card: 2 * 60 * 60_000,
  practice: 2 * 60 * 60_000,
  story: 3 * 60 * 60_000,
  explainer: 3 * 60 * 60_000,
  discussion: 4 * 60 * 60_000,
  article: 6 * 60 * 60_000,
};

export interface PublishWindow {
  /** Час выпуска в МСК, `HH:MM`. */
  time: string;
  /** Сколько окно остаётся открытым после этого часа. */
  toleranceMs: number;
  /** Какое время суток досталось классу — попадает в план и в сводку. */
  daypart: Daypart;
}

export function platformAudience(platform: PlanChannel): AudienceProfile {
  return PLATFORM_AUDIENCE[platform];
}

/** Суббота и воскресенье в терминах `Date.getUTCDay()` / `getDay()`. */
export function isWeekend(weekday: number): boolean {
  return weekday === 0 || weekday === 6;
}

/**
 * Окно выпуска для одного материала.
 *
 * `taken` — времена суток, уже занятые на этой площадке в этот день. Параметр
 * оставлен входом, а не состоянием модуля: функция обязана быть чистой, иначе
 * план перестанет быть воспроизводимым, а тест — возможным.
 *
 * Возвращает `null`, когда у площадки не осталось свободного времени суток.
 * Молчаливо ставить второй материал на тот же час нельзя: два поста в одну
 * минуту читаются как сбой, а не как расписание.
 */
export function publishWindow(input: {
  platform: PlanChannel;
  contentClass: ContentClass;
  weekday: number;
  taken?: readonly Daypart[];
}): PublishWindow | null {
  const audience = PLATFORM_AUDIENCE[input.platform];
  if (!audience) return null;
  const taken = new Set(input.taken ?? []);
  const weekend = isWeekend(input.weekday);

  for (const daypart of CLASS_DAYPARTS[input.contentClass]) {
    const hours = audience.dayparts[daypart];
    if (!hours || taken.has(daypart)) continue;
    return {
      time: weekend ? hours.weekend : hours.weekday,
      toleranceMs: CLASS_TOLERANCE_MS[input.contentClass],
      daypart,
    };
  }

  // Предпочтения класса исчерпаны — берём любое свободное время суток площадки.
  // Материал уже написан под эту площадку, и выпуск не в своё время суток
  // честнее, чем пропущенный слот (правило B636 «поздно честнее, чем никогда»).
  for (const daypart of ["morning", "midday", "evening", "late"] as const) {
    const hours = audience.dayparts[daypart];
    if (!hours || taken.has(daypart)) continue;
    return {
      time: weekend ? hours.weekend : hours.weekday,
      toleranceMs: CLASS_TOLERANCE_MS[input.contentClass],
      daypart,
    };
  }
  return null;
}

export function slotToleranceMsFor(contentClass: ContentClass): number {
  return CLASS_TOLERANCE_MS[contentClass];
}
