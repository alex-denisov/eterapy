import { AGENT_KPIS, type KpiAgent } from "@/lib/marketing/kpi";

const TITLES: Record<KpiAgent, string> = {
  seo: "SEO-агент",
  smm: "SMM-агент",
  orchestrator: "Оркестратор",
};

export function renderKpiTable(): string {
  const lines: string[] = [
    "# Контракт KPI агентов",
    "",
    "<!-- Сгенерировано: npm run kpi:table. Руками не правьте: источник правды —",
    "     web/src/lib/marketing/kpi.ts, по нему считает код. -->",
    "",
    "Изложение для чтения. **Источник правды — `web/src/lib/marketing/kpi.ts`.**",
    "Точка отсчёта у каждой метрики — живой замер, а не желание; дата замера",
    "указана в колонке «база».",
    "",
  ];

  for (const agent of ["seo", "smm", "orchestrator"] as const) {
    const own = AGENT_KPIS.filter((kpi) => kpi.agent === agent);
    if (own.length === 0) continue;
    lines.push(`## ${TITLES[agent]}`, "");
    lines.push("| Метрика | Ед. | Куда | База | Месяц | Квартал | Год |");
    lines.push("| --- | --- | --- | --- | --- | --- | --- |");
    for (const kpi of own) {
      lines.push(
        `| ${kpi.title} | ${kpi.unit} | ${kpi.direction === "up" ? "↑" : "↓"} `
        + `| ${kpi.baseline.value} (${kpi.baseline.measuredAt}) `
        + `| ${kpi.targets.month} | ${kpi.targets.quarter} | ${kpi.targets.year} |`,
      );
    }
    lines.push("");
    for (const kpi of own) {
      lines.push(`- **${kpi.title}.** ${kpi.why} _Источник: ${kpi.source}._`);
    }
    lines.push("");
  }

  lines.push(
    "## Два правила, без которых эти числа ничего не значат",
    "",
    "**1. У каждого агента есть ограничитель** — метрика, которая портится, если",
    "гнать основную. Без него KPI «больше страниц» выполняется выпуском мусора:",
    "корпус из 199 карточек с медианой 65 собственных слов набрался ровно так.",
    "",
    "**2. Разрыв меняет условия работы, а не формулировку задачи.** Отставание по",
    "глубине корпуса поднимает суточную норму выпуска; просевшая уникальность",
    "опускает её обратно и делает это сильнее, чем отставание по количеству",
    "поднимает. Правки идут через тот же белый список границ (1…8 страниц в",
    "сутки), что и прочие правки оркестратора, и откатываются одной командой.",
    "",
    "## Чего здесь пока нет честно",
    "",
    "Метрики без замера в отчёте так и называются — «без замера», а не нулём.",
    "Ноль и «не измерили» — разные утверждения, и путаница между ними уже стоила",
    "панели доверия (B649): пустой график читался как «нас не показывают», хотя",
    "означал «мы не спрашивали».",
    "",
  );

  return lines.join("\n");
}
