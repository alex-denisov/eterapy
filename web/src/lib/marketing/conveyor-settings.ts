import db from "@/lib/db";
import { MARKETING_MAX_AWAITING_REVIEW } from "@/lib/marketing/conveyor-tact";

/** Ключ настройки. Тот же, что в белом списке оркестратора. */
export const MAX_AWAITING_REVIEW_SETTING_KEY = "marketing.conveyor.max_awaiting_review";

/** Границы — те же, что у оркестратора: ноль остановил бы линию целиком. */
export const MAX_AWAITING_REVIEW_MIN = 2;
export const MAX_AWAITING_REVIEW_MAX = 12;

/**
 * Потолок очереди редактора на сейчас.
 *
 * Порядок источников обычный для этого контура: строка в базе сильнее
 * окружения, окружение сильнее умолчания. Нечитаемое значение — это не повод
 * останавливать линию: берётся то, что было бы без настройки вовсе.
 */
export async function marketingMaxAwaitingReview(): Promise<number> {
  // `?.` здесь не паранойя, а тот же приём, что в `platform-settings.ts`:
  // сводка конвейера собирается и в прогонах с узким мокем базы, и отсутствие
  // таблицы настроек не должно превращаться в отказ сводки.
  const row = await db.platformSetting
    ?.findUnique({ where: { key: MAX_AWAITING_REVIEW_SETTING_KEY }, select: { value: true } })
    ?.catch(() => null);
  const parsed = Number(row?.value);
  if (!Number.isFinite(parsed)) return MARKETING_MAX_AWAITING_REVIEW;
  return Math.min(MAX_AWAITING_REVIEW_MAX, Math.max(MAX_AWAITING_REVIEW_MIN, Math.round(parsed)));
}
