/**
 * B599 · Матрица маркетинговых событий.
 *
 * Владелец: «пушить нотификации рекламного характера: с продажами, допродажами,
 * напоминания о начисленных баллах… каждое событие нужно категоризировать».
 *
 * ПОЧЕМУ МАТРИЦА — КОД, А НЕ ТАБЛИЦА В БАЗЕ. Реклама уходит наружу и необратима.
 * Список того, что мы вообще имеем право отправить, должен приезжать выкаткой и
 * проходить ревью, а не редактироваться в админке между делом. В базе живёт
 * ЖУРНАЛ отправленного, а не разрешение отправлять.
 *
 * ⚠ ЭТОТ ФАЙЛ — ПРЕДЛОЖЕНИЕ НА ПРИЁМКУ. Пока `MARKETING_NOTIFICATIONS` выключен,
 * ни одно из этих сообщений не уходит: матрица видна на экране в админке именно
 * для того, чтобы владелец вычеркнул лишнее ДО первой отправки.
 */

/** Категория — то, чем владелец фильтрует журнал и по чему судит о нагрузке. */
export type MarketingCategory =
  | "points" // про баллы: начислены, сгорают, закончились
  | "upsell" // допродажа к уже полученному результату
  | "winback" // возвращение после паузы
  | "completion" // человек начал и не закончил
  | "referral" // реферальная механика
  | "subscription" // покупка, продление и переход между тарифами
  | "promo" // акции и разовые кампании владельца
  | "content"; // материалы: новые статьи, новые услуги

export type MarketingChannel = "email" | "telegram" | "push";

export interface MarketingEventSpec {
  key: string;
  category: MarketingCategory;
  /** Кому это уходит. Отдельным полем: половина ошибок рассылок — не текст, а адресат. */
  audience: string;
  /** Человеческим языком: когда именно это уходит. Показывается в админке. */
  trigger: string;
  /**
   * Что запускает отправку в коде.
   *  - `automatic` — событие в приложении или ночной джоб; человека не требует.
   *  - `manual` — кампания, которую владелец запускает руками.
   * Различие не косметическое: автоматическое обязано иметь охлаждение, ручное
   * обязано иметь человека, который отвечает за отправку.
   */
  fire: "automatic" | "manual";
  /** Каналы в порядке предпочтения — берётся первый доступный человеку. */
  channels: MarketingChannel[];
  /** Не чаще одного раза в N дней НА ЧЕЛОВЕКА по этому событию. */
  minDaysBetween: number;
  subject: string;
  /**
   * Тело письма. Плейсхолдеры вида `{name}` подставляет отправитель; текст
   * хранится здесь целиком, чтобы владелец читал ровно то, что уйдёт.
   */
  body: string;
  /**
   * Почему это уместно. Не украшение: половина кандидатов из тикета отсеялась
   * именно на этом вопросе, и следующий, кто захочет добавить событие, должен
   * ответить на него же.
   */
  rationale: string;
}

