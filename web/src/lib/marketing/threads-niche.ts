const compile = (words: readonly string[]) => new RegExp(`${B}(?:${words.join("|")})${E}`, "iu");
const PRACTICE_RE = compile(PRACTICE_WORDS);
const PSYCH_RE = compile(PSYCH_WORDS);

export type NichePole = "practice" | "psych" | "blend";

/** Целевая доля постов ленты, держащих тему. */
export const NICHE_TARGET_SHARE = 0.8;

export function touchesNiche(text: string): boolean {
  return PRACTICE_RE.test(text) || PSYCH_RE.test(text);
}

/** Какой полюс темы несёт пост: практики, психология, оба сразу; `null` — тема не затронута. */
export function nichePole(text: string): NichePole | null {
  const practice = PRACTICE_RE.test(text);
  const psych = PSYCH_RE.test(text);
  if (practice && psych) return "blend";
  if (practice) return "practice";
  return psych ? "psych" : null;
}

/** Окно ленты, по которому выбираем полюс следующего поста. */
const POLE_WINDOW = 8;

/**
 * Полюс следующего поста: тот, которого в последних постах меньше. Решение
 * владельца: ни перекоса в гадания, ни в психотерапию. Нет разницы — смесь.
 */
export function suggestPole(recentTexts: readonly string[]): NichePole {
  const poles = recentTexts.slice(-POLE_WINDOW).map(nichePole);
  const practice = poles.filter((pole) => pole === "practice").length;
  const psych = poles.filter((pole) => pole === "psych").length;
  if (practice - psych >= 2) return "psych";
  if (psych - practice >= 2) return "practice";
  return "blend";
}

/** Доля постов, держащих тему; `null` — постов нет. */
export function nicheShare(texts: readonly string[]): number | null {
  const posts = texts.filter((text) => text.trim().length > 0);
  if (posts.length === 0) return null;
  return posts.filter(touchesNiche).length / posts.length;
}

/** Замечание кругу правки: пост ушёл от темы. Не отказ — владелец видит пост на премодерации (B764). */
export function nicheFindings(text: string): LimitViolation[] {
  if (!text.trim() || touchesNiche(text)) return [];
  return [{
    kind: "contract",
    rule: "threads-off-niche",
    issue: "Пост не про нашу тему: нет ни психологии (границы, тревога, самооценка, ссора, терапия), ни мягких практик (таро, знаки, планеты, Луна, число судьбы).",
    brief: "Вплети в сцену нашу оптику изнутри — одной деталью, а не плашкой: что здесь происходит с границами, "
      + "тревогой или самооценкой, ИЛИ что показал бы расклад, где стоит Луна, что значит число. Сцена и герои остаются, "
      + "меняется взгляд. Не «добавь гороскоп в конец».",
  }];
}

/** Ядро: отношения и самопознание — то, с чем к нам приходят чаще всего. */
const CORE_AREAS = new Set([
  "бывший", "нынешние отношения", "свидания и знакомства", "ссоры и конфликты", "измена и доверие",
  "развод и расставание", "самопознание", "эго и самооценка", "границы", "суеверия и приметы", "индустрия гаданий",
]);
/** Остатки прежнего списка: сцены без повода связать их с темой. */
const PERIPHERAL_AREAS = new Set([
  "соседи", "транспорт", "маркетплейсы и доставка", "питомцы", "быт", "отпуск", "сезон и погода",
  "праздники и подарки", "дни рождения", "переезд и жильё", "внешность и спорт",
]);

/** Множитель веса области при выборе сцены: ядро ×1.5, периферия ×0.4, остальное и новое ×1. */
export function areaTierWeight(area: string): number {
  const key = area.toLocaleLowerCase("ru-RU").trim();
  if (CORE_AREAS.has(key)) return 1.5;
  if (PERIPHERAL_AREAS.has(key)) return 0.4;
  return 1;
}

