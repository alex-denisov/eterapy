/**
 * B771 — тематический якорь ленты Threads.
 *
 * Замер сухого прогона B762 (16 постов): даже по самому мягкому признаку —
 * в тексте есть знак, карта, Луна, расклад — тему держали 6 из 16 (38%), и
 * большая часть попаданий случайная («гороскоп от банка»). Разведчик искал
 * «жизнь аудитории 20–35», 28 областей включали соседей и транспорт, а вес
 * форматов отдавал около трети ленты нашей теме. Решение владельца (B766):
 * посты «по существу» — механики платформы (таро, астрология, нумерология,
 * матрица судьбы, дизайн человека, совместимость) как призма над отношениями и
 * самопознанием. Форматы, хуки и приёмы — свободны; тема — нет.
 *
 * Здесь: признак темы по тексту, доля темы по ленте, замечание кругу правки и
 * вес области жизни по близости к теме.
 */

import type { LimitViolation } from "@/lib/marketing/platform-limits";

const B = "(?<![а-яё])";
const E = "(?![а-яё])";

/** Слова нашей темы; корни обрезаны под падежи, границы — lookaround (`\b` с кириллицей не работает). */
const NICHE_WORDS = [
  "таро\\w*", "таролог[а-яё]*", "расклад[а-яё]*", "аркан[а-яё]*", "колод[а-яё]*",
  "гороскоп[а-яё]*", "астролог[а-яё]*", "астрологи[а-яё]*", "зодиак[а-яё]*", "натал[а-яё]*",
  "нумеролог[а-яё]*", "числ[а-яё]* судьбы", "матриц[а-яё]* судьбы", "дизайн[а-яё]* человека",
  "ретроград[а-яё]*", "меркури[а-яё]*", "венер[а-яё]*", "марс[а-яё]*", "сатурн[а-яё]*", "плутон[а-яё]*",
  "планет[а-яё]*", "затмени[а-яё]*", "луна", "луны", "луне", "луну", "луной", "полнолуни[а-яё]*", "новолуни[а-яё]*",
  "совместимост[а-яё]*", "карт[аыуе] дня", "знак[а-яё]* зодиака",
  "овн[а-яё]*", "тельц[а-яё]*", "телец", "близнец[а-яё]*", "рак", "рак(?:а|у|ом|е|и|ов|ам|ами|ах)", "л[еь]в(?:а|у|ом|е|ы|ов|ам|ами|ах)?",
  "дев(?:а|ы|е|у|ой|ам|ами|ах)", "весы", "весов", "весам", "весах", "скорпион[а-яё]*", "стрел[ье]ц[а-яё]*", "козерог[а-яё]*", "водоле[а-яё]*",
  "рыбы", "рыб", "рыбам", "рыбами", "рыбах", "гадани[а-яё]*", "гадалк[а-яё]*", "гадат[а-яё]*",
];
const NICHE_RE = new RegExp(`${B}(?:${NICHE_WORDS.join("|")})${E}`, "iu");

/** Целевая доля постов ленты, держащих тему. */
export const NICHE_TARGET_SHARE = 0.8;

export function touchesNiche(text: string): boolean {
  return NICHE_RE.test(text);
}

/** Доля постов, держащих тему; `null` — постов нет. */
export function nicheShare(texts: readonly string[]): number | null {
  const posts = texts.filter((text) => text.trim().length > 0);
  if (posts.length === 0) return null;
  return posts.filter(touchesNiche).length / posts.length;
}

/** Замечание кругу правки: пост ушёл от темы. Не отказ — владелец видит пост на премодерации (B764). */
export function nicheFindings(text: string): LimitViolation[] {
  if (!text.trim() || touchesNiche(text)) return [];
  return [{
    kind: "contract",
    rule: "threads-off-niche",
    issue: "Пост не про нашу тему: нет ни таро, ни знаков, ни планет, ни Луны, ни расклада, ни числа судьбы.",
    brief: "Вплети в сцену нашу механику изнутри — одной деталью, а не плашкой: что показал расклад, что сказал бы знак, "
      + "где стоит Луна, что значит число. Сцена и герои остаются, меняется оптика. Не «добавь гороскоп в конец».",
  }];
}

/** Области, которые читателю нашей темы ближе всего: отношения, суеверия, гадание, самооценка. */
const CORE_AREAS = new Set([
  "бывший", "нынешние отношения", "свидания и приложения", "подруги", "самооценка и возраст",
  "суеверия и приметы", "индустрия гаданий", "ожидание против реальности", "родители и детство", "сон и ночь",
]);
/** Области, где без усилия получается пост «про жизнь вообще». */
const PERIPHERAL_AREAS = new Set([
  "соседи", "транспорт", "маркетплейсы и доставка", "питомцы", "быт", "отпуск", "сезон и погода",
  "праздники и подарки", "дни рождения", "переезд и жильё", "внешность и спорт",
]);

/** Множитель веса области при выборе сцены: ядро ×1.5, периферия ×0.4, остальное и новое ×1. */
export function areaTierWeight(area: string): number {
  const key = area.toLocaleLowerCase("ru-RU").trim();
  if (CORE_AREAS.has(key)) return 1.5;
  if (PERIPHERAL_AREAS.has(key)) return 0.4;
  return 1;
}
