/** День недели (0 — воскресенье … 6 — суббота) → полезный формат главного вечернего слота. */
const USEFUL_BY_WEEKDAY: ReadonlyMap<number, PostFormat> = new Map([
  [1, MYTH_TRUTH_FORMAT],
  [3, MINI_PRACTICE_FORMAT],
  [5, CHECKLIST_CHAIN_FORMAT],
]);

export function usefulFormatForWeekday(weekday: number): PostFormat | null {
  return USEFUL_BY_WEEKDAY.get(weekday) ?? null;
}

export const USEFUL_FORMATS: readonly PostFormat[] = [MYTH_TRUTH_FORMAT, MINI_PRACTICE_FORMAT, CHECKLIST_CHAIN_FORMAT];

/** День недели суток эпохи (0 — воскресенье): 1970-01-01 был четвергом. */
export function weekdayOfDayNumber(day: number): number {
  return (((day + 4) % 7) + 7) % 7;
}
