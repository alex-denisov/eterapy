/**
 * B731 — СОДЕРЖИМОЕ МОКАПА ПЕРЕПИСКИ: живой диалог, а не библиотечные фразы.
 *
 * Требование владельца 2026-09-08 дословно: «Мне нужны максимально живые
 * диалоги на скриншотах, на любую тему, отношения, работа, родительство, брак,
 * измены, друзья […] не "библиотечными" разговорами с отточенными правильными
 * фразами, а именно так, как общаются обычные люди друг с другом, включая маты
 * (ругательства) […] скобки, многоточия, реплики с большой и с маленькой буквы,
 * знаки препинания которые могут отсутствовать или же быть чрезмерно большого
 * количества».
 *
 * Отсюда три решения.
 *
 * 1. ТЕМА, А НЕ ОДИН ПУЛ НА ВСЁ. Проверка на стенде показала, почему: вокруг
 *    реплики «Почему застрял проект?» стояли «мне тоже тяжело» и «Я не хочу так
 *    больше» — переписка про отношения поверх делового вопроса. Тема
 *    определяется по кластеру и тексту материала, и от неё зависит И подпись
 *    собеседника, И реплики: «Свекровь» уместна в родительстве и абсурдна в
 *    рабочем чате.
 *
 * 2. НЕРОВНОСТЬ ЗАПИСАНА В САМИ РЕПЛИКИ. Строчная буква в начале, пропущенная
 *    точка, «))))», «?????», многоточие, опечатка, мат — всё это здесь текстом,
 *    а не «стилем», который накладывается сверху. Так его видно на ревью и
 *    можно править построчно.
 *
 * 3. МАТ ЕСТЬ, НО ЕГО ДОЛЯ ОГРАНИЧЕНА. Реплики с матом собраны в отдельные
 *    списки и подставляются реже обычных (`PROFANITY_CHANCE`). Так живость
 *    остаётся, а лента не выглядит сплошной руганью.
 *    ⚠ Модерация площадок к мату относится по-разному: Meta и VK могут
 *    ограничить показы. Ручка одна и здесь — если владелец скажет «убрать»,
 *    достаточно обнулить `PROFANITY_CHANCE`.
 *
 * Фоновые реплики намеренно НЕ несут фактов: ничего, что можно принять за
 * свидетельство о реальном человеке, в них нет
 * ([[feedback_demo_stats_become_fabrication]]).
 */

