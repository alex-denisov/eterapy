/** Как площадка относится к прямому призыву. */
import type { InlineLinkMarkup } from "@/lib/marketing/link-presentation";

export type CtaPolicy =
  /** Призыв обязателен в каждом материале. */
  | "required"
  /** Призыв уместен, но не в каждом материале — норма задана `ctaShareOfPosts`. */
  | "sparing"
  /** Призыв по умолчанию дефект: он стоит нам охвата или нарушает нормы места. */
  | "discouraged";

export interface PlatformContract {
  /** Ниже этого материал не набирает дочитывания и выглядит обрубком. */
  minCharacters: number;
  /** Предел готового текста ВМЕСТЕ со ссылкой; `null` — предела нет. */
  maxCharacters: number | null;
  /**
   * Сколько символов видно до обрезки лентой. Весь смысловой крючок обязан
   * уложиться сюда: в VK лента режет на «показать полностью», в Instagram —
   * на «ещё», в Telegram столько видно в превью уведомления.
   */
  hookCharacters: number;
  /** Предел заголовка; `null` — у площадки нет отдельного заголовка. */
  maxTitleCharacters: number | null;
  maxParagraphs: number;
  maxParagraphCharacters: number;
  /** Подзаголовок обязателен каждые N символов; `null` — подзаголовки не нужны. */
  subheadingEveryCharacters: number | null;
  mediaBriefRequired: boolean;
  minHashtags: number;
  maxHashtags: number;
  maxEmoji: number;
  ctaPolicy: CtaPolicy;
  /**
   * Норма частоты призыва при `ctaPolicy` = "sparing"/"discouraged":
   * доля материалов площадки, в которых призыв уместен.
   */
  ctaShareOfPosts: number;
  /**
   * Раньше какой доли текста призыв и ссылка стоять не должны. У Дзена ранняя
   * ссылка роняет показ материала в ленте — это не стиль, а потеря охвата.
   */
  ctaMinPosition: number;
  /** Сколько ссылок допустимо в теле материала. */
  maxLinks: number;
  /** Кликабельна ли ссылка в теле. Instagram — единственная, где нет. */
  linksClickable: boolean;
  /**
   * B719 — умеет ли площадка прятать адрес под текст, и какой разметкой.
   *
   * `null` значит «в теле поста только голый адрес». Это не про кликабельность:
   * ВКонтакте ссылку кликабельной делает, а гиперссылку в тексте — нет.
   */
  inlineLinkMarkup: InlineLinkMarkup;
  /**
   * Допустим ли символ «—» вообще.
   *
   * B705, поправка владельца 2026-08-12: «—» отсутствует на клавиатуре, его
   * нельзя поставить естественным путём, и человек в поле ввода набирает «-».
   * Значит на площадках, где текст печатают руками в поле, наличие «—» — это
   * прямой признак машины, а не вопрос плотности.
   *
   * Исключение ровно одно: редактор Дзена делает автотипографику сам, и «—»
   * появляется там без участия автора. Там правило неприменимо.
   */
  emDashAllowed: boolean;
  maxEllipsis: number;
  maxExclamations: number;
}

export interface PlatformPlaybook {
  contract: PlatformContract;
  /** Кто читает и в каком состоянии — одна фраза. */
  audience: string;
  /** Что площадка делает для нас: привлекает, удерживает или снабжает сырьём. */
  role: string;
  /** Проза для системного промта автора. Только про эту площадку. */
  briefing: string;
}

