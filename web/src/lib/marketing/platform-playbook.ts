/**
 * Заведён ли плейбук для площадки.
 *
 * Отдельная проверка нужна `inspectDraft`: у площадки без плейбука проверять
 * нечего. Проницаемых ЧИСЕЛ для этого мало — правила про штампы, симметрию
 * абзацев и конкретные якоря чисел не имеют и сработали бы всё равно, выдав
 * замечания по контракту, которого никто не писал.
 */
export function hasPlatformPlaybook(platform: string): boolean {
  return platform.trim().toLowerCase() in PLATFORM_PLAYBOOKS;
}

export function platformPlaybook(platform: string): PlatformPlaybook {
  return PLATFORM_PLAYBOOKS[platform.trim().toLowerCase()] ?? DEFAULT_PLAYBOOK;
}

export function platformContract(platform: string): PlatformContract {
  return platformPlaybook(platform).contract;
}

/**
 * Числа контракта в том виде, в каком они уходят в задачу автору.
 *
 * Дублирование прозы и чисел намеренное: проза объясняет ПОЧЕМУ, числа задают
 * ГРАНИЦУ. Замер прода показал, что одной прозы мало — «не более 480 символов»
 * стояло в промте, и автор писал 718.
 */
export function platformContractForPrompt(platform: string): Record<string, unknown> {
  const playbook = platformPlaybook(platform);
  const c = playbook.contract;
  return {
    platform,
    audience: playbook.audience,
    roleOfChannel: playbook.role,
    characters: { min: c.minCharacters, max: c.maxCharacters },
    hookMustFitInCharacters: c.hookCharacters,
    maxTitleCharacters: c.maxTitleCharacters,
    paragraphs: { max: c.maxParagraphs, maxCharactersEach: c.maxParagraphCharacters },
    subheadingEveryCharacters: c.subheadingEveryCharacters,
    mediaBriefRequired: c.mediaBriefRequired,
    hashtags: { min: c.minHashtags, max: c.maxHashtags },
    maxEmoji: c.maxEmoji,
    cta: {
      policy: c.ctaPolicy,
      shareOfPosts: c.ctaShareOfPosts,
      notEarlierThanShareOfText: c.ctaMinPosition,
    },
    links: { max: c.maxLinks, clickable: c.linksClickable },
    typography: {
      emDashAllowed: c.emDashAllowed,
      emDashRule: c.emDashAllowed
        ? "редактор площадки сам расставляет типографику, длинное тире допустимо"
        : "символа «—» на клавиатуре нет: человек здесь набирает обычный дефис «-». "
          + "Длинное тире в этом поле ввода — прямой признак машинного текста. Не ставь его.",
      maxEllipsis: c.maxEllipsis,
      maxExclamations: c.maxExclamations,
    },
  };
}

