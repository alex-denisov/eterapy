    "«Если коротко» — назови суть ТОЧНЕЕ, чем это сформулировал сам человек. Не пересказ. Он должен подумать «да, это точнее, чем я сам сказал». Если абзац подошёл бы другому человеку с той же темой — он плохой, перепиши.",
