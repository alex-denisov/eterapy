export interface SeoBackfillBrief {
  /** Вопрос страницы. Менять нельзя. */
  question: string;
  /** Короткий ответ, который уже стоит на странице. */
  summary: string;
  topic: LibraryTopic;
  ctaProduct: string;
  ctaPromise: string;
  ctaPath: string;
  /** Что уже есть на странице кроме короткого ответа. */
  existingPoints: readonly string[];
}

export function seoLibraryBackfillPrompt(
  brief: SeoBackfillBrief,
  revisionNotes: readonly string[] = [],
): string {
  const lines = [
    `ВОПРОС СТРАНИЦЫ (не меняй): «${brief.question}»`,
    `КОРОТКИЙ ОТВЕТ, который уже стоит на странице (не пересказывай): ${brief.summary}`,
    `ТЕМА КАТАЛОГА: ${brief.topic}`,
    `УСЛУГА ДЛЯ ПЕРЕХОДА: «${brief.ctaProduct}» — ${brief.ctaPromise}. Адрес: ${brief.ctaPath}`,
  ];
  if (brief.existingPoints.length > 0) {
    lines.push(
      "УЖЕ СКАЗАНО НА СТРАНИЦЕ (не повторяй, отталкивайся дальше):",
      ...brief.existingPoints.map((point) => `— ${point}`),
    );
  }
  if (revisionNotes.length > 0) {
    lines.push(
      "",
      "ЗАМЕЧАНИЯ ПРОШЛОГО РАУНДА — устрани их:",
      ...revisionNotes.map((note) => `— ${note}`),
    );
  }
  return lines.join("\n");
}
