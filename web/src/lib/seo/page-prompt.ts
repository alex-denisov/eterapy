export function seoLibraryEditorPrompt(input: {
  brief: SeoPageBrief;
  draftJson: string;
  machineFindings: readonly string[];
  round: number;
  previousNotes: readonly string[];
}): string {
  const lines = [
    `ЗАПРОС: «${input.brief.targetQuery}»`,
    `РАУНД: ${input.round}`,
    "",
    "МАТЕРИАЛ:",
    input.draftJson,
    "",
    input.machineFindings.length > 0
      ? `machineFindings (уже посчитано машиной, пересчитывать не надо):\n${input.machineFindings.map((item) => `— ${item}`).join("\n")}`
      : "machineFindings: нарушений формата нет.",
  ];
  if (input.previousNotes.length > 0) {
    lines.push(
      "",
      "ТВОИ ЖЕ ЗАМЕЧАНИЯ ПРОШЛОГО РАУНДА — проверь, устранены ли они:",
      ...input.previousNotes.map((note) => `— ${note}`),
    );
  }
  return lines.join("\n");
}

