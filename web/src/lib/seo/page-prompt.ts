export function seoLibraryWriterPrompt(brief: SeoPageBrief, revisionNotes: readonly string[] = []): string {
  const demand = brief.monthlyDemand !== null
    ? `${brief.monthlyDemand} показов в месяц`
    : "частотность не измерена";
  const growth = brief.growth !== null
    ? `, рост ${Math.round(brief.growth * 100)}%`
    : "";
  const lines = [
    `ЗАПРОС: «${brief.targetQuery}» (${demand}${growth})`,
    `ТЕМА КАТАЛОГА: ${brief.topic}`,
    `УСЛУГА ДЛЯ ПЕРЕХОДА: «${brief.ctaProduct}» — ${brief.ctaPromise}. Адрес: ${brief.ctaPath}`,
  ];
  if (brief.recentTitles.length > 0) {
    lines.push(
      "УЖЕ ВЫШЛО ПО ЭТОЙ ТЕМЕ (не повторяй угол и заголовок):",
      ...brief.recentTitles.map((title) => `— ${title}`),
    );
  }
  if (revisionNotes.length > 0) {
    lines.push(
      "",
      "ЗАМЕЧАНИЯ РЕДАКТОРА ПРОШЛОГО РАУНДА — устрани их, а не перепиши материал заново:",
      ...revisionNotes.map((note) => `— ${note}`),
    );
  }
  return lines.join("\n");
}

