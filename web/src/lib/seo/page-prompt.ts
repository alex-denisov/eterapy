export interface SeoPageBrief {
  /** Запрос, под который пишется страница, в том виде, как его набирают люди. */
  targetQuery: string;
  /** Показов в месяц, если измерено. */
  monthlyDemand: number | null;
  /** Рост, если известен. */
  growth: number | null;
  /** Тема каталога. */
  topic: LibraryTopic;
  /** Название услуги, в которую страница обязана конвертировать. */
  ctaProduct: string;
  /** Что эта услуга делает — одной фразой, чтобы автор не выдумывал. */
  ctaPromise: string;
  /** Адрес услуги на сайте. */
  ctaPath: string;
  /** Заголовки уже вышедших материалов той же темы — чтобы не повторяться. */
  recentTitles: readonly string[];
}

