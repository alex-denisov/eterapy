/** Нормализация для сверки: нижний регистр, ё→е в запасной копии не нужна. */
function normalize(phrase: string): string {
  return phrase
    .toLocaleLowerCase("ru-RU")
    .replace(/[«»"'`.,!?:;()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

