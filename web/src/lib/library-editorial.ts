function compactQuestion(question: string, maxLength = 54): string {
  const normalized = question.replace(/[«»]/g, "").trim();
  if (normalized.length <= maxLength) return normalized;
  const shortened = normalized.slice(0, maxLength - 1).replace(/\s+\S*$/, "").trim();
  return `${shortened}…`;
}

function compactText(text: string, maxLength: number): string {
  const normalized = text.replace(/\s+/g, " ").trim();
  if (normalized.length <= maxLength) return normalized;
  const shortened = normalized.slice(0, maxLength - 1).replace(/\s+\S*$/, "").replace(/[,:;.!?]+$/, "").trim();
  return `${shortened}…`;
}

export function libraryMetaTitle(entry: AnonymousLibraryEntry): string {
  return entry.seo?.metaTitle ?? `${compactQuestion(entry.question)} | ETerapy`;
}

export function libraryMetaDescription(entry: AnonymousLibraryEntry): string {
  return compactText(
    entry.seo?.metaDescription ?? `${entry.summary} Короткий разбор и первый безопасный шаг.`,
    158,
  );
}
