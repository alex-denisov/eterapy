/**
 * B599 (батч №20) · Срок отмены удаления аккаунта — ОДНО число на всю платформу.
 *
 * Найдено при сборке каталога служебных событий: человеку называли ТРИ разных
 * срока. Настройки кабинета обещали 10 дней, справка — 30, а чистка данных
 * (`RETENTION_POLICY.accountProfile.softDeleteGraceDays`) шла через 7. То есть
 * тот, кто передумал на восьмой день и пришёл ровно в обещанный срок, находил
 * аккаунт уже обезличенным.
 *
 * Взято 10 дней, а не 7: это то, что мы людям обещали. Срок, названный
 * пользователю, сокращать задним числом нельзя — в отличие от продления, у
 * которого пострадавших нет.
 *
 * Модуль намеренно пустой от зависимостей: его читают и клиентские настройки, и
 * серверная чистка. Второе объявление этого числа где угодно — это возврат к
 * трём срокам.
 */
export const ACCOUNT_SOFT_DELETE_GRACE_DAYS = 10;

/** Дата безвозвратного удаления для запроса, поданного в `requestedAt`. */
export function accountPurgeDate(requestedAt: Date): Date {
  return new Date(requestedAt.getTime() + ACCOUNT_SOFT_DELETE_GRACE_DAYS * 86_400_000);
}
