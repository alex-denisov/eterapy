/** B750 — одна страница на намерение: близкие формулировки каннибализируют выдачу. */
import { duplicateOf, nearDuplicate, topicKey } from "@/lib/seo/demand/duplicates";
import { relevanceVerdict } from "@/lib/seo/demand/relevance";

describe("B750 topicKey / nearDuplicate", () => {
  it("варианты одного намерения совпадают", () => {
    const group = [
      "как быстро принять решение",
      "как принять какое то решение",
      "как можно принять решение",
      "как принять нужное решение",
      "как принять наилучшее решение",
      "как принимать хорошие решения",
      "выбор как принять решения",
    ];
    for (const a of group) for (const b of group) expect(nearDuplicate(a, b)).toBe(true);
  });
  it("фамилия и расшифровка: наполнители не мешают", () => {
    expect(nearDuplicate("фамилия значение происхождение", "значение и происхождение фамилии")).toBe(true);
    expect(nearDuplicate("дизайн человека расшифровка бесплатно", "дизайн человека с расшифровкой онлайн")).toBe(true);
  });
  it("разные ситуации не склеиваются", () => {
    expect(nearDuplicate("муж изменил что делать", "жена изменила что делать")).toBe(false);
    expect(nearDuplicate("токсичные отношения с мужем", "токсичные отношения с мамой")).toBe(false);
    expect(nearDuplicate("как забыть бывшего", "как пережить развод")).toBe(false);
  });
  it("пустой ключ не склеивает разное, ключ детерминирован", () => {
    expect(nearDuplicate("как можно", "что делать")).toBe(false);
    expect(topicKey("Как принять решение")).toBe(topicKey("как  принять, решение?"));
  });
  it("duplicateOf возвращает фразу-образец", () => {
    expect(duplicateOf("как принять важное решение", ["жена ушла что делать", "как быстро принять решение"])).toBe(
      "как быстро принять решение",
    );
    expect(duplicateOf("муж молчит", ["как быстро принять решение"])).toBeNull();
  });
});

describe("B750 деловой контекст блокируется, личный выбор проходит", () => {
  it.each([
    "как принимать решения руководителю",
    "как принимать решения в бизнесе",
    "как менеджеру принимать решения",
    "как мотивировать сотрудников",
    "как принять решение по проекту",
  ])("блок: %s", (p) => expect(relevanceVerdict(p)).not.toBeNull());
  it.each(["как принять решение о разводе", "как принять решение уйти от мужа", "муж бизнесмен не бывает дома что делать"])(
    "проходит: %s",
    (p) => expect(relevanceVerdict(p)).toBeNull(),
  );
});
