/** B750 — ложные отказы живым ситуативным запросам (ревью координатора). */
import { relevanceVerdict } from "@/lib/seo/demand/relevance";

const MUST_PASS = [
  "как забыть бывшего",
  "как пережить развод",
  "почему муж молчит",
  "боюсь остаться одна",
  "мне 40 и я одинока что делать",
  "сезонная депрессия что делать",
  "муж бизнесмен не бывает дома что делать",
  "муж играет в игры что делать",
  "война со свекровью что делать",
  "право на счастье после развода",
  "курс лечения не помогает тревога что делать",
  "муж изменил что делать",
];

const MUST_FAIL = [
  "17 аркан на год",
  "токсичные отношения 4",
  "дизайн человека какие",
  "когда закончится война на украине предсказания",
  "арканы дота 2",
];

describe("B750 regression: границы слов и короткие вопросы", () => {
  it.each(MUST_PASS)("пропускает: %s", (p) => expect(relevanceVerdict(p)).toBeNull());
  it.each(MUST_FAIL)("отсекает: %s", (p) => expect(relevanceVerdict(p)).not.toBeNull());
});
