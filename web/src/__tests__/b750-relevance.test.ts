/**
 * B750 — в очередь страниц идут запросы на разбор ситуации, а не темы выдачи.
 * Фразы взяты из живой очереди 2026-10-05 (490 строк, из них ~80% мусор).
 */
import { relevanceVerdict } from "@/lib/seo/demand/relevance";

const KEPT = [
  "что делать если муж изменяет",
  "муж изменяет но не уходит",
  "как выйти из токсичных отношений с мужчиной",
  "что значит токсичные отношения",
  "что такое токсичные отношения",
  "как быстро принять решение",
  "к чему снится бывший муж",
  "как понять что он меня не любит",
  "почему муж не хочет разговаривать со мной",
  "как узнать происхождение своей фамилии",
  "расшифровка матрицы судьбы",
  "ворота дизайна человека",
  "каналы в дизайне человека",
  "что значит 6 аркан в матрице судьбы",
  "стоит ли прощать измену мужа",
];

const REJECTED = [
  "арканы дота 2",
  "натальная карта смотреть шоу",
  "токсичные отношения манхва",
  "токсичные отношения глава 66",
  "печенье с предсказаниями",
  "когда закончится война на украине предсказания",
  "предсказания на 2026 год для россии",
  "вопросы семейного права",
  "семейный кодекс вопросы",
  "вопрос семейное положение",
  "происхождение фамилии путин",
  "происхождение фамилии абрамов",
  "натальная карта азамата мусагалиева",
  "русская жена изменила мужу",
  "жена изменяет мужу видео",
  "изменила мужа с друга",
  "таро новое сегодня",
  "приму решение как",
  "перл таро сентябрь",
  "17 аркан на год",
  "как суд принимает решение",
  "матрица судьбы рассчитать онлайн бесплатно",
];

describe("B750 relevanceVerdict", () => {
  it.each(KEPT)("берёт: %s", (phrase) => {
    expect(relevanceVerdict(phrase)).toBeNull();
  });

  it.each(REJECTED)("отсекает с причиной: %s", (phrase) => {
    const verdict = relevanceVerdict(phrase);
    expect(typeof verdict).toBe("string");
    expect((verdict ?? "").length).toBeGreaterThan(5);
  });

  it("границы слов работают с кириллицей: «сво» не ловит «своей»", () => {
    expect(relevanceVerdict("как понять что делать со своей ревностью")).toBeNull();
  });

  it("«судьбы» не принимается за «суд»", () => {
    expect(relevanceVerdict("что значит матрица судьбы для пары")).toBeNull();
  });
});
