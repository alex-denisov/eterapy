/**
 * B705 §11.4 — пять правил `blader/humanizer`, перенесённых в машинную проверку.
 *
 * Каждое правило проверяется парой: срабатывание на признаке машины И молчание
 * на живом русском тексте, где та же конструкция законна. Вторая половина
 * пары важнее первой: ложное замечание стоит целого раунда правки — ровно той
 * траты, ради снятия которой заведён `draft-inspection.ts`.
 */

import { inspectDraft } from "@/lib/marketing/draft-inspection";

function rulesFor(text: string, extra: Partial<Parameters<typeof inspectDraft>[0]> = {}) {
  return inspectDraft({
    platform: "telegram",
    title: "Повторяющийся сон",
    text,
    cta: "Разобрать свой сон за пять минут",
    mediaBrief: "тёмная спальня, мягкий рассветный свет",
    destinationUrl: "https://eterapy.com/products/dreams",
    ...extra,
  }).map((defect) => defect.rule);
}

describe("B705 §11.4 · правило трёх", () => {
  it("две триады в одном материале — замечание", () => {
    const text =
      "Сон повторяется, тревожит и не отпускает. Вы просыпаетесь в 4 утра, лежите и ждёте. "
      + "Помогает не толкование, а наблюдение: что было днём, что вы чувствовали, о чём молчали. "
      + "Запишите одну деталь.";
    expect(rulesFor(text)).toContain("rule-of-three");
  });

  it("одна триада — обычный русский, замечания нет", () => {
    const text =
      "Сон повторяется, тревожит и не отпускает. Повтор не предсказывает событие: он показывает, "
      + "какая тема держит вас наяву. Запишите одну деталь через 5 минут после пробуждения — "
      + "именно её вы забудете первой.";
    expect(rulesFor(text)).not.toContain("rule-of-three");
  });
});

describe("B705 §11.4 · ложный диапазон", () => {
  it("«от тревоги до апатии» — риторическая фигура, замечание", () => {
    const text =
      "Один и тот же сон тянет за собой всё: от тревоги до апатии. Повтор не предсказывает "
      + "событие. Запишите деталь через 5 минут после пробуждения.";
    expect(rulesFor(text)).toContain("false-range");
  });

  it("измеримый диапазон «от 5 до 10 минут» замечанием не считается", () => {
    const text =
      "Запишите сон в первые от 5 до 10 минут после пробуждения. Позже память достроит сюжет "
      + "и вы запомните пересказ, а не сам сон.";
    expect(rulesFor(text)).not.toContain("false-range");
  });
});

describe("B705 §11.4 · оформление", () => {
  it("избыток жирного ловится, а одно выделение — нет", () => {
    const bold =
      "**Первое** правило простое. **Второе** тоже. **Третье** и **четвёртое** добавлены "
      + "для ритма, которого в живом тексте не бывает. Запишите деталь через 5 минут.";
    expect(rulesFor(bold)).toContain("bold-over");

    const single =
      "Повтор сна не предсказывает событие. **Важно другое**: какая тема держит вас наяву "
      + "и почему именно она возвращается ночью. Запишите деталь через 5 минут после пробуждения.";
    expect(rulesFor(single)).not.toContain("bold-over");
  });

  it("список «**Заголовок:** пояснение» — форма справки, а не поста", () => {
    const text =
      "Что делать с повторяющимся сном.\n\n"
      + "- **Записать:** первые 5 минут после пробуждения решают всё.\n"
      + "- **Не толковать:** символ сам по себе ничего не доказывает.\n";
    expect(rulesFor(text)).toContain("bold-list-header");
  });
});

describe("B705 §11.4 · артефакты переписки", () => {
  it("хвост из чата снимается", () => {
    const text =
      "Повтор сна не предсказывает событие: он показывает, какая тема держит вас наяву. "
      + "Запишите деталь через 5 минут после пробуждения.\n\nНадеюсь, было полезно!";
    expect(rulesFor(text)).toContain("chat-artifact");
  });

  it("живой текст без формул вежливости замечания не получает", () => {
    const text =
      "Повтор сна не предсказывает событие: он показывает, какая тема держит вас наяву. "
      + "Запишите деталь через 5 минут после пробуждения — именно её вы забудете первой.";
    expect(rulesFor(text)).not.toContain("chat-artifact");
  });
});

describe("B705 §11.4 · граница переноса", () => {
  it("незнакомая площадка новых правил тоже не получает", () => {
    // B640: площадка без плейбука не изобретает себе ограничений — новые
    // правила эту границу не сдвигают.
    const text = "**А:** раз. **Б:** два. **В:** три. Надеюсь, было полезно!";
    expect(rulesFor(text, { platform: "mastodon" })).toEqual([]);
  });
});
