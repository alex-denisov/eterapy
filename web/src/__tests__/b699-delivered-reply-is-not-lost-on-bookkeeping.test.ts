/**
 * Ответ доставлен — учёт не имеет права это отменить.
 *
 * ЖИВОЙ СЛУЧАЙ 2026-08-08 (владелец): «я подтвердил, ответ даже успешно ушёл, а
 * в админке застряло как требует ответа». Разбор: второй ответ ОДНОМУ И ТОМУ ЖЕ
 * человеку в VK получил тот же `public_url` — это адрес диалога, а не адрес
 * ответа, — и запись упала на уникальности. Материал ушёл в архив, входящее
 * осталось открытым, а человек ответ уже получил.
 *
 * Здесь держатся два свойства:
 *   1. адрес ответа в VK уникален для каждого сообщения;
 *   2. столкновение адресов не превращает доставленное в отказ.
 */

import { vkDirectReplyUrl } from "@/lib/marketing/inbound-reply";

describe("адрес ответа в личных сообщениях VK", () => {
  it("у двух ответов одному человеку адреса разные", () => {
    const first = vkDirectReplyUrl({ communityId: "240493895", peerId: "1059391948", messageId: "12" });
    const second = vkDirectReplyUrl({ communityId: "240493895", peerId: "1059391948", messageId: "37" });

    expect(first).not.toBe(second);
  });

  it("адрес по-прежнему открывает нужный диалог", () => {
    expect(vkDirectReplyUrl({ communityId: "240493895", peerId: "1059391948", messageId: "12" }))
      .toBe("https://vk.com/gim240493895?sel=1059391948#msg12");
  });
});
