-- B588 (owner 2026-07-26): «Каталог демо-профилей — оставляем только по 2 профилю
-- каждого направления (эзотерика и психология), остальные отключаем».
--
-- B584 закрыл к сидированным профилям запись, но каталог продолжал показывать
-- тринадцать «специалистов». Остаются четыре: по два на направление. Остальные
-- девять (пять эзотерики, две психологии, две коучинга) уходят из выдачи.
--
-- Механизм — статус, а не новый флаг: `status = 'ACTIVE'` уже является единым
-- фильтром каталога, страницы профиля, sitemap, рекомендательных блоков, тизера
-- на лендинге и мини-аппа. Введение отдельной «видимости в каталоге» добавило бы
-- второй источник правды к тому же вопросу. `SUSPENDED` доступен суперадминке
-- (карточка пользователя, селект «Деактивирован»/«Активен»), поэтому решение
-- обратимо без миграции.
--
-- Список — по почте, а не по слагу: слаг генерируется из имени и может измениться,
-- почта же определяется провижинингом демо-аккаунтов. Единый источник списка —
-- `web/src/lib/demo-catalog.ts` (его же читают сиды).

UPDATE "practitioners" p
SET "status" = 'SUSPENDED'
FROM "users" u
WHERE u."id" = p."userId"
  AND p."demo_account" = true
  AND p."status" = 'ACTIVE'
  AND lower(u."email") NOT IN (
    'practitioner@test.eterapy.com', -- эзотерика: астрология + нумерология
    'tarot@test.eterapy.com',        -- эзотерика: таро
    'psy-cbt@test.eterapy.com',      -- психология: КПТ + схема-терапия
    'psy-family@test.eterapy.com'    -- психология: системная семейная
  );

