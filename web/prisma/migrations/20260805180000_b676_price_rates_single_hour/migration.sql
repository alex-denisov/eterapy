-- B676 · цена сессии живёт в `price_rates`, а не в `practitioners`.
--
-- Найдено живой проверкой стенда, а не тестом: после первой миграции карточка
-- Алисы по-прежнему показывала «от 2 000 ₽ / 45 мин», хотя
-- `practitioners."pricePerSession"` уже равнялся 10 000. Витрина и оформление
-- записи берут цену из `price_rates` — по одной строке на длительность
-- (15/30/45/60/90/120), и показывают МИНИМАЛЬНУЮ включённую. Поле на самом
-- практике осталось от прежней модели и на цену не влияет.
--
-- Владелец 2026-08-05: «Стоимость выставь в 10000 руб за 1 час, других
-- вариантов не делай. Остальным всем практикам на платформе сделай стоимость
-- 60 минут 9000 руб».
--
-- Поэтому: у ВСЕХ остаётся включённой ровно одна длительность — час. Иначе
-- «других вариантов не делай» не выполняется буквально, а у остальных
-- витрина продолжила бы показывать «от 2 000 ₽ / 45 мин» рядом с ценой часа
-- в 9 000 ₽.
--
-- Идемпотентно: повторный прогон перезапишет те же значения.

-- Все длительности, кроме часа, выключены у всех.
UPDATE price_rates SET enabled = false WHERE "durationMin" <> 60;

-- Час: 10 000 ₽ Алисе, 9 000 ₽ остальным.
UPDATE price_rates r
SET "priceRub" = CASE WHEN p.slug = 'alisa-babaeva' THEN 10000 ELSE 9000 END,
    enabled = true
FROM practitioners p
WHERE p.id = r."practitionerId"
  AND r."durationMin" = 60;

-- Строка часа может отсутствовать у профиля, заведённого до появления сетки.
INSERT INTO price_rates (id, "practitionerId", "durationMin", "priceRub", enabled)
SELECT 'rate_hour_' || p.id, p.id, 60,
       CASE WHEN p.slug = 'alisa-babaeva' THEN 10000 ELSE 9000 END, true
FROM practitioners p
ON CONFLICT ("practitionerId", "durationMin") DO NOTHING;
