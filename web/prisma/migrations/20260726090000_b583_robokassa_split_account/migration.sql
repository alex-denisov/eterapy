-- B583: адресат сплита Robokassa у специалиста.
--
-- Robokassa не умеет откладывать выплату — только холдировать платёж клиента, —
-- и сплитует ТОЛЬКО на аккаунт Robokassa получателя. Поэтому у специалиста
-- появляется идентификатор его аккаунта Robokassa; банковские реквизиты выше
-- остаются для фискальной части и ручной выплаты.
--
-- Оба поля nullable: у действующих специалистов аккаунта ещё нет, и выплата им
-- должна оставаться возможной вручную, а не падать после миграции.
ALTER TABLE "payout_details" ADD COLUMN "robokassa_account" TEXT;
ALTER TABLE "payout_details" ADD COLUMN "robokassa_verified_at" TIMESTAMP(3);
