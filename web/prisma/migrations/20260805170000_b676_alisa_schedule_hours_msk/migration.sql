-- B676 · поправка часов расписания Алисы: 10:00–19:00 МОСКОВСКОГО времени.
--
-- Найдено живой проверкой стенда, а не тестом. `generatePotentialSlots` строит
-- слот из `new Date("2026-09-10T10:00:00")` — БЕЗ суффикса зоны, то есть в
-- локальном времени процесса. Контейнер живёт в UTC (`date` → `UTC`), а
-- клиентская часть печатает время без `timeZone`, то есть в зоне браузера.
-- Значит правило «10–19» давало московскому клиенту 13:00–22:00.
--
-- Правило хранит часы в UTC, поэтому 10:00–19:00 MSK = 07:00–16:00.
--
-- ⚠ Это свойство ПЛАТФОРМЫ, а не одной строки: у `schedule_rules` нет часового
-- пояса вовсе. Пока живой специалист один и он в Москве, поправка значениями
-- честна и достаточна. Второй специалист в другой зоне потребует колонки
-- часового пояса у практика — отдельная работа, названа в B676.
--
-- Отдельной миграцией, а не правкой предыдущей: та уже применена на стенде и
-- записана в `_prisma_migrations`; изменение её текста дало бы расхождение
-- контрольной суммы (P3006), а не исправление.

UPDATE schedule_rules r
SET "startHour" = 7, "endHour" = 16
FROM practitioners p
WHERE p.id = r."practitionerId"
  AND p.slug = 'alisa-babaeva';
