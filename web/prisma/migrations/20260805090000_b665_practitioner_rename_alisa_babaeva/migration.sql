-- B665 — демо-профиль «Елена Морозова» становится реальным практиком
-- «Алиса Бабаева» (решение владельца 2026-08-05).
--
-- Переименование, а не новый профиль: у адреса /practitioners/elena-morozova
-- есть накопленный трафик, и владелец прямо просил заменить ссылки без
-- переадресации. Старый адрес после этой миграции честно перестаёт
-- существовать — сторож адресов (B600) сверяется с каталогом, а не с файлами
-- маршрутов.
--
-- Вместе с именем снимаются ВЫДУМАННЫЕ данные витрины: 15 отзывов, рейтинг и
-- 120 проведённых сессий. Под демо-именем это была витрина; под именем живого
-- человека это были бы сфабрикованные отзывы о конкретном специалисте, чего
-- быть не должно ни при каких обстоятельствах.
--
-- Профиль остаётся закрытым для записи (`demo_account` не трогаем): владелец
-- 2026-08-05 — «пока пользователей нет, нет смысла её онбордить». Открытие
-- слотов с 10 сентября — отдельное решение и отдельная правка.
--
-- Миграция идемпотентна: повторный прогон не найдёт старого слага и не сделает
-- ничего.

UPDATE users u
SET name = 'Алиса Бабаева'
FROM practitioners p
WHERE p."userId" = u.id
  AND p.slug = 'elena-morozova';

DELETE FROM reviews r
USING practitioners p
WHERE r."practitionerId" = p.id
  AND p.slug = 'elena-morozova';

UPDATE practitioners
SET slug = 'alisa-babaeva',
    title = 'Таролог · Астролог · Нумеролог',
    bio = 'Работаю с картами Таро, натальной картой и нумерологическим разбором. В консультации важен не прогноз, а опора: посмотреть на ситуацию со стороны и увидеть следующий шаг. Отдельно веду темы тревоги, отношений и выборов, из которых трудно выйти.',
    experience = '10 лет',
    specialties = ARRAY['TAROT', 'ASTROLOGY', 'NUMEROLOGY']::"Specialty"[],
    -- Каталог фильтрует по taxonomy-колонкам, а не по `specialties`: без этой
    -- строки практик остался бы невидим в фильтре «Таро».
    categories = ARRAY['esoteric'],
    directions = ARRAY['tarot', 'astrology', 'numerology'],
    "ratingSum" = 0,
    "reviewCount" = 0,
    "sessionCount" = 0
WHERE slug = 'elena-morozova';
