--
-- Дословно: «нам пока не нужны никакие данные по практикам (потому что у
-- Robokassa выплаты идут через собственные механизмы связки личных кабинетов,
-- мы это проходили уже). По поводу email — пока оставляем как есть, все
-- остальное — уже можно считать настоящим практиком».
--
-- ЧТО ЭТО МЕНЯЕТ. Коммерческий гейт (`evaluatePractitionerCommercialGate`)
-- требовал у живого специалиста ИНН, подтверждённый налоговый статус,
-- реквизиты выплаты и магазин Robokassa. Без них оплата сессии упиралась в
-- гейт, а слоты при этом показывались.
--
-- ПОЧЕМУ ЧЕРЕЗ `booking_override_enabled`, А НЕ СНОСОМ ПРОВЕРОК. Механизм
-- ручного открытия записи уже существует (B459) и делает ровно то, что просит
-- владелец: пропускает КОММЕРЧЕСКИЕ требования и не трогает статус профиля и
-- демо-признак. Он адресный, виден в админке и снимается одним переключателем.
-- Снос самих проверок открыл бы оплату всем будущим специалистам молча и без
-- следа решения — а владелец сказал «пока», то есть на нынешний момент.
--
-- Оферта: `agent_offer_version` в первой миграции записан как 'v1', а гейт
-- ждёт 'agent-offer-2026-07-20'. Приводим к актуальной версии — чтобы, когда
-- override снимут, профиль не упал на проверке, которую он на деле проходит.
--
-- Что НЕ делается здесь: e-mail профиля остаётся practitioner@test.eterapy.com
-- по прямому указанию владельца.

UPDATE practitioners
SET booking_override_enabled = true,
    agent_offer_accepted_at  = COALESCE(agent_offer_accepted_at, NOW()),
    agent_offer_version      = 'agent-offer-2026-07-20'
WHERE slug = 'alisa-babaeva';
