-- B591 фаза 3 (owner 2026-07-27): «нужно убрать все платежи, которые не были
-- реальными».
--
-- Мерчантом ЮKassa платформа не была НИКОГДА: рельс существовал только в коде и
-- в тестовых прогонах. При этом в `transactions` за май–июль лежит 61 строка с
-- `provider = 'yookassa'` — 33 «успешные» на 55 073 ₽, 17 отменённых и 11
-- висящих. Ни по одной не приходило денег ни одной секунды.
--
-- Почему это опаснее, чем просто мусор в таблице. Книга доходов и панель
-- «сколько отложить» строятся по этой таблице. Отсечка по дате запуска рельса
-- (22.07.2026, Robokassa) убрала их из суммы дохода, но строки остались видны
-- как платежи: в панели платежей, в карточке пользователя, в любом будущем
-- отчёте, который забудет про отсечку. Налог платится с того, что в выгрузке.
--
-- Реальных денег на проде до этой даты — одна оплата на 299 ₽ (Robokassa,
-- 26.07.2026). Она остаётся. Внутренние проводки (`internal`) — тоже: это не
-- платежи, а движение по счёту внутри платформы, и в доход они не попадают.
--
-- Строки перед удалением выгружены в CSV и лежат в work-log тикета B591;
-- ночные бэкапы базы содержат их целиком.

DELETE FROM transactions WHERE provider IN ('yookassa', 'yukassa');

-- Платёж, помеченный тестовым (B571), реальным не был по определению.
DELETE FROM transactions WHERE test_mode = true;

-- Подписки, «оплаченные» тем же несуществующим рельсом. Доступ снимать нельзя:
-- на нём держатся тестовые аккаунты, через которые проверяется прод. Но
-- утверждать, что за него платили через ЮKassa, тоже нельзя — источник
-- становится честным: доступ выдан платформой.
UPDATE user_subscriptions SET provider = 'internal' WHERE provider IN ('yookassa', 'yukassa');
